static struct p_sq sq;
static char pb[160];
static char dbuf[32768];

#define MAXN 400
static char names[MAXN][24];
static u8 types[MAXN];

/* Read a whole directory with getdents64 buffers of `bufsz` bytes; returns the entry count
 * (or -errno), and the number of getdents64 calls that returned data in *calls. */
static int list(const char *path, size_t bufsz, int *calls) {
    i64 fd = a_open(path, O_RDONLY | O_DIRECTORY, 0);
    if (fd < 0) return (int)fd;
    int n = 0;
    *calls = 0;
    for (;;) {
        i64 r = syscall3(SYS_getdents64, fd, dbuf, bufsz);
        if (r < 0) {
            a_close(fd);
            return (int)r;
        }
        if (r == 0) break;
        (*calls)++;
        for (i64 off = 0; off < r;) {
            struct a_dirent64 *e = (struct a_dirent64 *)(dbuf + off);
            if (n < MAXN) {
                size_t i = 0;
                while (e->d_name[i] && i < 23) {
                    names[n][i] = e->d_name[i];
                    i++;
                }
                names[n][i] = 0;
                types[n] = e->d_type;
            }
            n++;
            off += e->d_reclen;
        }
    }
    a_close(fd);
    return n;
}

static int index_of(const char *name, int n) {
    for (int i = 0; i < n && i < MAXN; i++)
        if (str_eq(names[i], name)) return i;
    return -1;
}

int test_main(void) {
    check("setup", p_sq_setup(&sq, D, img, sizeof img, 0, 0) == 0, 0);
    expect("mount", p_sq_mount(&sq), 0);
    int calls = 0;

    int n = list(sq.mnt, sizeof dbuf, &calls);
    expect("root_entry_count_22", n, 22);
    static const char *want[] = {".", "..", "big.bin", "blk", "chr", "dir", "dlink", "empty", "fifo", "hard1",
                                 "hard2", "hello.txt", "link", "longlink", "loop1", "loop2", "many", "owned",
                                 "sparse.bin", "suid", "tmp", "xa"};
    static const u8 want_type[] = {DT_DIR, DT_DIR, DT_REG, DT_BLK, DT_CHR, DT_DIR, DT_LNK, DT_REG, DT_FIFO,
                                   DT_REG, DT_REG, DT_REG, DT_LNK, DT_LNK, DT_LNK, DT_LNK, DT_DIR, DT_REG,
                                   DT_REG, DT_REG, DT_DIR, DT_REG};
    int order_ok = 1, type_ok = 1;
    for (int i = 0; i < 22 && i < n; i++) {
        if (!str_eq(names[i], want[i])) order_ok = 0;
        if (types[i] != want_type[i]) type_ok = 0;
    }
    check("root_names_in_order", order_ok, 0);
    check("root_d_types", type_ok, 0);

    /* small buffers: same listing, in several calls */
    int n2 = list(sq.mnt, 100, &calls);
    expect("small_buffer_count", n2, 22);
    check("small_buffer_needs_many_calls", calls > 2, calls);
    order_ok = 1;
    for (int i = 0; i < 22 && i < n2; i++)
        if (!str_eq(names[i], want[i])) order_ok = 0;
    check("small_buffer_same_order", order_ok, 0);
    expect("tiny_buffer_einval", list(sq.mnt, 8, &calls), -EINVAL);

    /* an empty directory, a nested directory */
    expect("tmp_count", list(p_sq_path(&sq, pb, "/tmp"), 4096, &calls), 2);
    check("tmp_dot_dotdot", str_eq(names[0], ".") && str_eq(names[1], ".."), 0);
    expect("dir_count", list(p_sq_path(&sq, pb, "/dir"), 4096, &calls), 4);
    check("dir_entries", str_eq(names[2], "a") && str_eq(names[3], "sub") && types[2] == DT_REG && types[3] == DT_DIR, 0);

    /* 300 entries */
    n = list(p_sq_path(&sq, pb, "/many"), sizeof dbuf, &calls);
    expect("many_count_302", n, 302);
    int ok = 1;
    for (int i = 0; i < 300; i++) {
        char want_name[8] = {'f', (char)('0' + i / 100), (char)('0' + i / 10 % 10), (char)('0' + i % 10), 0};
        if (!str_eq(names[i + 2], want_name) || types[i + 2] != DT_REG) ok = 0;
    }
    check("many_sorted_regular_files", ok, 0);
    n = list(p_sq_path(&sq, pb, "/many"), 200, &calls);
    expect("many_small_buffer_count", n, 302);
    check("many_small_buffer_many_calls", calls > 10, calls);
    ok = 1;
    for (int i = 0; i < 300; i++) {
        char want_name[8] = {'f', (char)('0' + i / 100), (char)('0' + i / 10 % 10), (char)('0' + i % 10), 0};
        if (!str_eq(names[i + 2], want_name)) ok = 0;
    }
    check("many_small_buffer_sorted", ok, 0);

    /* their contents: one hexadecimal digit of (index mod 16) */
    char c = 0;
    char path[160];
    str_cat2(path, sq.mnt, "/many/f017");
    i64 fd = a_open(path, O_RDONLY, 0);
    expect("read_f017", a_read(fd, &c, 1), 1);
    expect("f017_is_1", c, '1');
    expect("f017_eof", a_read(fd, &c, 1), 0);
    a_close(fd);
    str_cat2(path, sq.mnt, "/many/f299");
    fd = a_open(path, O_RDONLY, 0);
    expect("read_f299", a_read(fd, &c, 1), 1);
    expect("f299_is_b", c, 'b');
    a_close(fd);

    /* seek and rewind on a directory */
    fd = a_open(sq.mnt, O_RDONLY | O_DIRECTORY, 0);
    i64 r1 = syscall3(SYS_getdents64, fd, dbuf, sizeof dbuf);
    check("first_pass", r1 > 0, r1);
    expect("second_pass_empty", syscall3(SYS_getdents64, fd, dbuf, sizeof dbuf), 0);
    expect("rewind", syscall3(SYS_lseek, fd, 0, SEEK_SET), 0);
    i64 r2 = syscall3(SYS_getdents64, fd, dbuf, sizeof dbuf);
    expect("same_size_after_rewind", r2, r1);
    check("first_entry_dot_after_rewind", str_eq(((struct a_dirent64 *)dbuf)->d_name, "."), 0);
    a_close(fd);

    fd = a_open(p_sq_path(&sq, pb, "/hello.txt"), O_RDONLY, 0);
    expect("getdents_on_file_enotdir", syscall3(SYS_getdents64, fd, dbuf, sizeof dbuf), -ENOTDIR);
    a_close(fd);
    (void)index_of;

    p_sq_teardown(&sq);
    return finish();
}
