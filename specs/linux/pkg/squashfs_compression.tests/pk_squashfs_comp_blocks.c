static struct p_sq sq;

static void one(const char *tag, const unsigned char *img, size_t len, u64 bsize) {
    char name[64];
    i64 r = p_sq_setup(&sq, "/tmp/pk_sc_blocks", img, len, 0, 0);
    check(str_cat2(name, tag, ":setup"), r == 0, r);
    if (r == 0) {
        r = p_sq_mount(&sq);
        check(str_cat2(name, tag, ":mount"), r == 0, r);
        if (r == 0) {
            struct a_statfs fs;
            memset(&fs, 0, sizeof fs);
            syscall2(SYS_statfs, sq.mnt, &fs);
            check(str_cat2(name, tag, ":f_bsize"), fs.f_bsize == (i64)bsize, fs.f_bsize);
            check(str_cat2(name, tag, ":f_blocks_1"), fs.f_blocks == 1, fs.f_blocks);
            p_small_check(tag, sq.mnt);
            struct a_stat st;
            char p[96];
            syscall2(SYS_stat, str_cat2(p, sq.mnt, "/pattern.txt"), &st);
            check(str_cat2(name, tag, ":st_blksize_1024"), st.st_blksize == 1024, st.st_blksize);
        }
    }
    p_sq_teardown(&sq);
}

