static struct p_sq sq;

int test_main(void) {
    p_small_case(&sq, "xz", "/tmp/pk_sc_xzzstd", img_xz, sizeof img_xz);
    /* zstd: the oracle kernel of the recording was built without zstd support for squashfs (the
     * mount fails with EINVAL and the kernel logs that zstd is not supported); Poly must mount it.
     * The test accepts both, and prints the same line either way. */
    i64 r = p_sq_setup(&sq, "/tmp/pk_sc_xzzstd", img_zstd, sizeof img_zstd, 0, 0);
    check("zstd:setup", r == 0, r);
    if (r == 0) {
        r = p_sq_mount(&sq);
        int ok = (r == -EINVAL) || (r == 0 && p_small_ok(sq.mnt));
        check("zstd:mounts_and_reads_or_is_unsupported", ok, r);
    }
    p_sq_teardown(&sq);
    return finish();
}
