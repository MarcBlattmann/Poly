fn size(t: &mut Test, label: &str, il: HIMAGELIST) {
    let (mut cx, mut cy) = (-1, -1);
    // SAFETY: two integers.
    let ok = unsafe { ImageList_GetIconSize(il, &mut cx, &mut cy) };
    say!(t, "{label}: count {} size {ok} {cx}x{cy}", unsafe { ImageList_GetImageCount(il) });
}

macro_rules! callv {
    ($t:expr, $label:expr, $e:expr) => {{
        let r = ($e) as i64;
        say!($t, "{}: {}", $label, r);
        r
    }};
}

poly_wtest::main!(test);

fn test(t: &mut Test) {
    // SAFETY: plain calls.
    unsafe { GetSystemMetrics(0) };
    unsafe { InitCommonControls() };
    let inst = instance();
    let il = unsafe { ImageList_Create(16, 16, ILC_COLOR32 | ILC_MASK, 2, 4) };
    say!(t, "ImageList_Create 16x16 ILC_COLOR32|ILC_MASK: {}", hwnd_kind(il));
    size(t, "new list", il);
    // a strip of three 4x4 images in one 12x4 bitmap
    let dib = [0u32; 48];
    let mk = |r: u8, g: u8, b: u8| -> [u32; 48] {
        let mut d = dib;
        for i in 0..48 {
            d[i] = 0xFF00_0000 | (r as u32) << 16 | (g as u32) << 8 | b as u32;
        }
        d
    };
    let _ = mk;
    // SAFETY: a DIB section, filled by hand.
    let strip = unsafe {
        let bi = BITMAPINFO { header: BITMAPINFOHEADER { size: 40, width: 12, height: -4, planes: 1, bit_count: 32, compression: 0, size_image: 0, x_pels_per_meter: 0, y_pels_per_meter: 0, clr_used: 0, clr_important: 0 }, colors: [0; 1] };
        let mut bits: *mut c_void = core::ptr::null_mut();
        let b = CreateDIBSection(core::ptr::null_mut(), &bi, 0, &mut bits, core::ptr::null_mut(), 0);
        let px = bits as *mut u32;
        for y in 0..4 {
            for x in 0..12 {
                *px.add(y * 12 + x) = if x < 4 { 0xFF0000 } else if x < 8 { 0x00FF00 } else { 0x0000FF };
            }
        }
        b
    };
    let il4 = unsafe { ImageList_Create(4, 4, ILC_COLOR32, 0, 1) };
    size(t, "4x4 list", il4);
    callv!(t, "ImageList_Add of a 3-image strip, no mask", unsafe { ImageList_Add(il4, strip, core::ptr::null_mut()) });
    size(t, "after Add", il4);
    callv!(t, "ImageList_AddMasked with the green as transparent", unsafe { ImageList_AddMasked(il4, strip, 0x00FF00) });
    size(t, "after AddMasked", il4);
    let icon = unsafe { LoadImageW(inst, mir(500), IMAGE_ICON, 16, 16, 0) } as HICON;
    let il16 = unsafe { ImageList_Create(16, 16, ILC_COLOR32 | ILC_MASK, 1, 1) };
    callv!(t, "ImageList_ReplaceIcon(-1) appends", unsafe { ImageList_ReplaceIcon(il16, -1, icon) });
    callv!(t, "ImageList_ReplaceIcon(-1) again", unsafe { ImageList_ReplaceIcon(il16, -1, icon) });
    callv!(t, "ImageList_ReplaceIcon(0) replaces", unsafe { ImageList_ReplaceIcon(il16, 0, icon) });
    callv!(t, "ImageList_ReplaceIcon(5) (past the end)", unsafe { ImageList_ReplaceIcon(il16, 5, icon) });
    size(t, "il16", il16);
    let got = unsafe { ImageList_GetIcon(il16, 1, ILD_NORMAL) };
    say!(t, "ImageList_GetIcon(1): {}", hwnd_kind(got));
    unsafe { DestroyIcon(got) };
    callv!(t, "ImageList_GetIcon(9) past the end", unsafe { ImageList_GetIcon(il16, 9, ILD_NORMAL) }.is_null() as i32);
    let mut info: IMAGEINFO = zeroed();
    callv!(t, "ImageList_GetImageInfo(1)", unsafe { ImageList_GetImageInfo(il16, 1, &mut info) });
    say!(t, "   image rect {}x{} at ({},{})", info.rc_image.right - info.rc_image.left, info.rc_image.bottom - info.rc_image.top, info.rc_image.left, info.rc_image.top);
    callv!(t, "ImageList_GetImageInfo(9)", unsafe { ImageList_GetImageInfo(il16, 9, &mut info) });
    callv!(t, "ImageList_Remove(0)", unsafe { ImageList_Remove(il16, 0) });
    size(t, "after Remove(0)", il16);
    callv!(t, "ImageList_Remove(7)", unsafe { ImageList_Remove(il16, 7) });
    callv!(t, "ImageList_SetImageCount(5)", unsafe { ImageList_SetImageCount(il16, 5) });
    size(t, "after SetImageCount(5)", il16);
    callv!(t, "ImageList_SetImageCount(1)", unsafe { ImageList_SetImageCount(il16, 1) });
    size(t, "after SetImageCount(1)", il16);
    callv!(t, "ImageList_Remove(-1) clears the list", unsafe { ImageList_Remove(il16, -1) });
    size(t, "after Remove(-1)", il16);
    let dup = unsafe { ImageList_Duplicate(il4) };
    say!(t, "ImageList_Duplicate: {} count {}", hwnd_kind(dup), unsafe { ImageList_GetImageCount(dup) });
    callv!(t, "background colour of a new list", unsafe { ImageList_GetBkColor(il4) } as u32 as i64);
    callv!(t, "ImageList_SetBkColor(CLR_NONE) returns the old one", unsafe { ImageList_SetBkColor(il4, CLR_NONE) } as u32 as i64);
    callv!(t, "now", unsafe { ImageList_GetBkColor(il4) } as u32 as i64);
    // creation arguments
    callv!(t, "Create 0x0", unsafe { ImageList_Create(0, 0, ILC_COLOR32, 1, 1) }.is_null() as i32);
    callv!(t, "Create 16x0", unsafe { ImageList_Create(16, 0, ILC_COLOR32, 1, 1) }.is_null() as i32);
    callv!(t, "Create -1x-1", unsafe { ImageList_Create(-1, -1, ILC_COLOR32, 1, 1) }.is_null() as i32);
    callv!(t, "Create 16x16 with 0 initial and 0 grow", unsafe { ImageList_Create(16, 16, ILC_COLOR32, 0, 0) }.is_null() as i32);
    callv!(t, "Create with flags 0 (device dependent default)", unsafe { ImageList_Create(16, 16, 0, 1, 1) }.is_null() as i32);
    // errors with handles
    callv!(t, "GetImageCount(NULL)", unsafe { ImageList_GetImageCount(core::ptr::null_mut()) });
    callv!(t, "GetImageCount(made up)", unsafe { ImageList_GetImageCount(0x1234 as HIMAGELIST) });
    callv!(t, "GetIconSize(NULL)", { let (mut a, mut b) = (0, 0); unsafe { ImageList_GetIconSize(core::ptr::null_mut(), &mut a, &mut b) } });
    callv!(t, "Add to NULL list", unsafe { ImageList_Add(core::ptr::null_mut(), strip, core::ptr::null_mut()) });
    callv!(t, "Destroy(NULL)", unsafe { ImageList_Destroy(core::ptr::null_mut()) });
    callv!(t, "Destroy il", unsafe { ImageList_Destroy(il) });
    callv!(t, "Destroy il again", unsafe { ImageList_Destroy(il) });
    callv!(t, "GetImageCount of a destroyed list", unsafe { ImageList_GetImageCount(il) });
    unsafe { ImageList_Destroy(il4) };
    unsafe { ImageList_Destroy(il16) };
    unsafe { ImageList_Destroy(dup) };
    unsafe { DeleteObject(strip) };
    unsafe { DestroyIcon(icon) };
}
