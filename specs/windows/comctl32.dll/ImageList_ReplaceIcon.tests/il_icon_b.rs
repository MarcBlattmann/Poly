fn strip(w: i32, h: i32, colors: &[u32]) -> HBITMAP {
    // SAFETY: a DIB section, filled by hand.
    unsafe {
        let n = colors.len() as i32;
        let bi = BITMAPINFO { header: BITMAPINFOHEADER { size: 40, width: w * n, height: -h, planes: 1, bit_count: 32, compression: 0, size_image: 0, x_pels_per_meter: 0, y_pels_per_meter: 0, clr_used: 0, clr_important: 0 }, colors: [0; 1] };
        let mut bits: *mut c_void = core::ptr::null_mut();
        let b = CreateDIBSection(core::ptr::null_mut(), &bi, 0, &mut bits, core::ptr::null_mut(), 0);
        let px = bits as *mut u32;
        for y in 0..h {
            for x in 0..w * n {
                *px.add((y * w * n + x) as usize) = colors[(x / w) as usize];
            }
        }
        b
    }
}

fn test(t: &mut Test) {
    // SAFETY: plain calls.
    unsafe { GetSystemMetrics(0) };
    unsafe { InitCommonControls() };
    let inst = instance();

    let ic = unsafe { LoadImageW(inst, mir(500), IMAGE_ICON, 16, 16, 0) } as HICON;
    let il = unsafe { ImageList_Create(16, 16, ILC_COLOR32 | ILC_MASK, 1, 1) };
    unsafe { ImageList_ReplaceIcon(il, -1, ic) };
    let a = unsafe { ImageList_GetIcon(il, 0, ILD_NORMAL) };
    let b = unsafe { ImageList_GetIcon(il, 0, ILD_NORMAL) };
    say!(t, "two icons: {} {} different handles {}", hwnd_kind(a), hwnd_kind(b), (a != b) as i32);
    let mut ii: ICONINFO = zeroed();
    unsafe { GetIconInfo(a, &mut ii) };
    let mut bm: BITMAP = zeroed();
    unsafe { GetObjectW(ii.hbm_color, 32, &mut bm as *mut BITMAP as *mut c_void) };
    say!(t, "icon from the list: fIcon {} size {}x{}", ii.f_icon, bm.width, bm.height);
    unsafe {
        let dc = CreateCompatibleDC(core::ptr::null_mut());
        let old = SelectObject(dc, ii.hbm_color);
        let c = GetPixel(dc, 4, 4);
        say!(t, "pixel (4,4) of the icon: #{:02x}{:02x}{:02x}", c & 0xFF, (c >> 8) & 0xFF, (c >> 16) & 0xFF);
        SelectObject(dc, old);
        DeleteDC(dc);
        DeleteObject(ii.hbm_color);
        DeleteObject(ii.hbm_mask);
    }
    let m = unsafe { ImageList_GetIcon(il, 0, ILD_MASK) };
    say!(t, "with ILD_MASK: {}", hwnd_kind(m));
    callv!(t, "index 1 (absent)", unsafe { ImageList_GetIcon(il, 1, ILD_NORMAL) }.is_null() as i32);
    callv!(t, "index -1", unsafe { ImageList_GetIcon(il, -1, ILD_NORMAL) }.is_null() as i32);
    callv!(t, "NULL list", unsafe { ImageList_GetIcon(core::ptr::null_mut(), 0, ILD_NORMAL) }.is_null() as i32);
    for h in [a, b, m] {
        unsafe { DestroyIcon(h) };
    }
    unsafe { ImageList_Destroy(il) };
    unsafe { DestroyIcon(ic) };
}
