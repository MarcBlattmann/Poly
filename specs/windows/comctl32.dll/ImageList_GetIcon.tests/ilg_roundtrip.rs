fn test(t: &mut Test) {
    // SAFETY: plain calls.
    unsafe { GetSystemMetrics(0) };
    unsafe { InitCommonControls() };
    unsafe {
        let inst = instance();
        let src = ImageList_Create(16, 16, ILC_COLOR32 | ILC_MASK, 2, 2);
        let ic = LoadImageW(inst, mir(500), IMAGE_ICON, 16, 16, 0) as HICON;
        say!(t, "ImageList_ReplaceIcon(-1) of the module icon: {}", ImageList_ReplaceIcon(src, -1, ic));
        say!(t, "count {}", count(src));
        let out = ImageList_GetIcon(src, 0, ILD_NORMAL);
        say!(t, "ImageList_GetIcon: {}", hwnd_kind(out));
        let dst = ImageList_Create(16, 16, ILC_COLOR32 | ILC_MASK, 2, 2);
        say!(t, "ImageList_ReplaceIcon(-1) of that icon: {}", ImageList_ReplaceIcon(dst, -1, out));
        // draw all three: the module icon, the list's image, the copy
        let (w, h) = (16, 16);
        let a = target(w, h, MAGENTA);
        let b = target(w, h, MAGENTA);
        let c = target(w, h, MAGENTA);
        DrawIconEx(a.0, 0, 0, ic, 16, 16, 0, core::ptr::null_mut(), 3);
        ImageList_Draw(src, 0, b.0, 0, 0, ILD_NORMAL);
        ImageList_Draw(dst, 0, c.0, 0, 0, ILD_NORMAL);
        let eq = |x: *mut u32, y: *mut u32| (0..(w * h) as usize).all(|i| *x.add(i) == *y.add(i));
        say!(t, "DrawIconEx of the icon equals ImageList_Draw of the list: {}", eq(a.2, b.2) as i32);
        say!(t, "the copy in the other list draws the same: {}", eq(b.2, c.2) as i32);
        samples(t, "icon", a.2, w, h, 0, 0, MAGENTA);
        samples(t, "list", b.2, w, h, 0, 0, MAGENTA);
        // the icon is not consumed by the list
        say!(t, "the module icon still works: GetIconInfo {}", { let mut ii: ICONINFO = zeroed(); GetIconInfo(ic, &mut ii) });
        say!(t, "DestroyIcon(out) {}", DestroyIcon(out));
        say!(t, "the list image is still drawn: {}", ImageList_Draw(dst, 0, c.0, 0, 0, ILD_NORMAL));
        // a size that differs from the list's
        let big = LoadImageW(inst, mir(500), IMAGE_ICON, 32, 32, 0) as HICON;
        say!(t, "ImageList_ReplaceIcon(-1) of a 32x32 icon in a 16x16 list: {}", ImageList_ReplaceIcon(dst, -1, big));
        say!(t, "count {}", count(dst));
        free_target(a);
        free_target(b);
        free_target(c);
        ImageList_Destroy(src);
        ImageList_Destroy(dst);
        DestroyIcon(ic);
        DestroyIcon(big);
    }
}
