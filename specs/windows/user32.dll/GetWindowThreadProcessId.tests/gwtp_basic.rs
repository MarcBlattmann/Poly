fn test(t: &mut Test) {
    let _cursor = CursorGuard::new();
    tag_register();
    // SAFETY: our windows, events and thread throughout.
    unsafe {
        let np = core::ptr::null_mut();
        let a = mkw(b'A', 0, WS_OVERLAPPEDWINDOW | WS_VISIBLE, 40, 40, 200, 150, np);
        let c = mkw(b'C', 0, WS_CHILD | WS_VISIBLE, 5, 5, 50, 50, a);
        let m = mkw(b'M', 0, WS_POPUP, 0, 0, 10, 10, HWND_MESSAGE);
        let me = (GetCurrentThreadId(), GetCurrentProcessId());
        for (label, h) in [("top-level", a), ("child", c), ("message-only", m)] {
            let mut pid = 0xFFFF_FFFFu32;
            set_error(0);
            let tid = GetWindowThreadProcessId(h, &mut pid);
            say!(t, "{label}: thread is ours: {} process is ours: {} (last error {})", (tid == me.0) as i32, (pid == me.1) as i32, last_error());
            set_error(0);
            let tid2 = GetWindowThreadProcessId(h, core::ptr::null_mut());
            say!(t, "{label}: without the pointer the thread is ours: {} (last error {})", (tid2 == me.0) as i32, last_error());
        }
        *STOP.get() = CreateEventW(core::ptr::null_mut(), 1, 0, core::ptr::null());
        *READY.get() = CreateEventW(core::ptr::null_mut(), 1, 0, core::ptr::null());
        let mut id = 0u32;
        let th = CreateThread(core::ptr::null_mut(), 0, thread_main, core::ptr::null_mut(), 0, &mut id);
        WaitForSingleObject(*READY.get(), 5000);
        let w2 = *OTHER_THREAD_WIN.get();
        let mut pid = 0u32;
        let tid = GetWindowThreadProcessId(w2, &mut pid);
        say!(t, "window of a second thread: thread differs from ours: {} equals the creating thread's: {} process is ours: {}", (tid != me.0) as i32, (tid == *OTHER_TID.get()) as i32, (pid == me.1) as i32);
        SetEvent(*STOP.get());
        WaitForSingleObject(th, 5000);
        CloseHandle(th);
        pid = 0;
        set_error(0);
        let tid = GetWindowThreadProcessId(w2, &mut pid);
        say!(t, "window of the finished thread (destroyed): thread={tid} pid={pid} (last error {})", last_error());
        let d = GetDesktopWindow();
        pid = 0;
        let tid = GetWindowThreadProcessId(d, &mut pid);
        say!(t, "desktop window: thread nonzero: {} process is ours: {}", (tid != 0) as i32, (pid == me.1) as i32);
        for (label, h) in [("NULL", np), ("a made-up handle", 0x1234usize as HWND)] {
            for start in [0u32, 0xFFFF_FFFF] {
                let mut pid = start;
                set_error(0);
                let tid = GetWindowThreadProcessId(h, &mut pid);
                say!(t, "{label}: pid output starting at {start:#x}: returns {tid} pid={pid:#x} (last error {})", last_error());
            }
        }
        DestroyWindow(a);
        let mut pid = 0xFFFF_FFFFu32;
        set_error(0);
        let tid = GetWindowThreadProcessId(a, &mut pid);
        say!(t, "destroyed window: returns {tid} pid={pid:#x} (last error {})", last_error());
        DestroyWindow(m);
    }
    settle(50);
}
