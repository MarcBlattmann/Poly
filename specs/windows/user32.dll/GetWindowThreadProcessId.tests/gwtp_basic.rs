//! GetWindowThreadProcessId (called about 380 times in a Chrome run): the
//! thread and process of windows of this test (equal to GetCurrentThreadId
//! and GetCurrentProcessId), with and without the process-id pointer, of a
//! window created on a second thread (its thread id differs, the process id
//! is the same), of the desktop window and of the shell's windows (another
//! process, another thread), of NULL and a made-up handle (0, ERROR_INVALID_WINDOW_HANDLE
//! 1400, the process id output left as it was or set to 0), of a destroyed
//! window, and of a message-only window. Only equalities are printed, no ids.
#![no_std]
#![no_main]
#![allow(dead_code, non_camel_case_types, clippy::all)]

