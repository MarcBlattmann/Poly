static OTHER_THREAD_WIN: Global<HWND> = Global::new(core::ptr::null_mut());
static OTHER_TID: Global<u32> = Global::new(0);
static STOP: Global<HANDLE> = Global::new(core::ptr::null_mut());
static READY: Global<HANDLE> = Global::new(core::ptr::null_mut());

unsafe extern "system" fn thread_main(_p: *mut c_void) -> u32 {
    // SAFETY: a window of this thread; the events are owned by the test.
    unsafe {
        *OTHER_TID.get() = GetCurrentThreadId();
        *OTHER_THREAD_WIN.get() = mkw(b'T', 0, WS_POPUP, 0, 0, 10, 10, core::ptr::null_mut());
        SetEvent(*READY.get());
        WaitForSingleObject(*STOP.get(), 5000);
        DestroyWindow(*OTHER_THREAD_WIN.get());
    }
    0
}

