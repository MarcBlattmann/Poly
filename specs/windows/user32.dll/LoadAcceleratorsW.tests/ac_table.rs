fn test(t: &mut Test) {
    // SAFETY: plain calls.
    unsafe { GetSystemMetrics(0) };
    let inst = instance();
    let a = unsafe { LoadAcceleratorsW(inst, mir(300)) };
    say!(t, "LoadAcceleratorsW(300): {}", hwnd_kind(a));
    entries(t, "resource 300", a);
    let named = unsafe { LoadAcceleratorsW(inst, wz!("ACCEL").as_ptr()) };
    say!(t, "LoadAcceleratorsW('ACCEL'): {}", hwnd_kind(named));
    entries(t, "resource ACCEL", named);
    // a table of our own
    let mine = [ACCEL { f_virt: FVIRTKEY, pad: 0, key: 0x71, cmd: 40 }, ACCEL { f_virt: 0, pad: 0, key: b'x' as u16, cmd: 41 }];
    let c = unsafe { CreateAcceleratorTableW(mine.as_ptr(), 2) };
    say!(t, "CreateAcceleratorTableW: {}", hwnd_kind(c));
    entries(t, "created", c);
    call!(t, "CreateAcceleratorTableW with count 0", unsafe { CreateAcceleratorTableW(mine.as_ptr(), 0) }.is_null() as i32);
    call!(t, "CreateAcceleratorTableW with a NULL array", unsafe { CreateAcceleratorTableW(core::ptr::null(), 2) }.is_null() as i32);
    // Copy variants
    let mut one = [ACCEL { f_virt: 0xEE, pad: 0xEE, key: 0xEEEE, cmd: 0xEEEE }; 2];
    call!(t, "CopyAcceleratorTableW with room for 1 of 5", unsafe { CopyAcceleratorTableW(a, one.as_mut_ptr(), 1) });
    call!(t, "CopyAcceleratorTableW with a NULL array (the count)", unsafe { CopyAcceleratorTableW(a, core::ptr::null_mut(), 0) });
    call!(t, "CopyAcceleratorTableW with a NULL array and a size", unsafe { CopyAcceleratorTableW(a, core::ptr::null_mut(), 5) });
    call!(t, "CopyAcceleratorTableW of a made-up handle", unsafe { CopyAcceleratorTableW(0x1234 as HACCEL, one.as_mut_ptr(), 2) });
    // translation
    register(wz!("AccWin"), Some(wproc), 0, 0, core::ptr::null_mut());
    let w = create(0, wz!("AccWin"), wz!("w"), WS_OVERLAPPEDWINDOW, 0, 0, 200, 100, core::ptr::null_mut(), 0);
    sendkey(t, w, a, WM_KEYDOWN, 0x70, "F1 key down (table 300)");
    sendkey(t, w, a, WM_KEYUP, 0x70, "F1 key up");
    sendkey(t, w, a, WM_KEYDOWN, 0x71, "F2 key down (not in the table)");
    sendkey(t, w, a, WM_CHAR, b'A' as usize, "WM_CHAR 'A' (a character accelerator)");
    sendkey(t, w, a, WM_CHAR, b'a' as usize, "WM_CHAR 'a'");
    sendkey(t, w, a, WM_KEYDOWN, b'A' as usize, "WM_KEYDOWN 'A' (a virtual key, the table has the character)");
    sendkey(t, w, a, WM_KEYDOWN, 0x4F, "'O' key down without Ctrl (the entry wants Ctrl)");
    sendkey(t, w, a, WM_KEYDOWN, 0x74, "F5 without Shift (the entry wants Shift)");
    sendkey(t, w, a, WM_SYSKEYDOWN, 0x0D, "Alt+Enter as WM_SYSKEYDOWN");
    sendkey(t, w, a, WM_SYSKEYDOWN, 0x70, "F1 as WM_SYSKEYDOWN");
    sendkey(t, w, c, WM_KEYDOWN, 0x71, "F2 (table made by CreateAcceleratorTableW)");
    sendkey(t, w, c, WM_CHAR, b'x' as usize, "WM_CHAR 'x'");
    sendkey(t, w, c, WM_CHAR, b'X' as usize, "WM_CHAR 'X'");
    sendkey(t, w, a, WM_MOUSEMOVE, 0, "a mouse message");
    sendkey(t, w, core::ptr::null_mut(), WM_KEYDOWN, 0x70, "a NULL table");
    sendkey(t, w, 0x1234 as HACCEL, WM_KEYDOWN, 0x70, "a made-up table");
    sendkey(t, core::ptr::null_mut(), a, WM_KEYDOWN, 0x70, "a NULL window");
    // destroy
    call!(t, "DestroyAcceleratorTable created", unsafe { DestroyAcceleratorTable(c) });
    call!(t, "destroy again", unsafe { DestroyAcceleratorTable(c) });
    call!(t, "NULL", unsafe { DestroyAcceleratorTable(core::ptr::null_mut()) });
    // load errors
    call!(t, "absent number", unsafe { LoadAcceleratorsW(inst, mir(999)) }.is_null() as i32);
    call!(t, "absent name", unsafe { LoadAcceleratorsW(inst, wz!("NOPE").as_ptr()) }.is_null() as i32);
    call!(t, "NULL module", unsafe { LoadAcceleratorsW(core::ptr::null_mut(), mir(300)) }.is_null() as i32);
    call!(t, "made-up module", unsafe { LoadAcceleratorsW(0x1000_0000 as HINSTANCE, mir(300)) }.is_null() as i32);
    unsafe { DestroyWindow(w) };
}
