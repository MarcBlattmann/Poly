static GOT: Global<u32> = Global::new(0);

unsafe extern "system" fn wproc(hwnd: HWND, msg: u32, w: WPARAM, l: LPARAM) -> LRESULT {
    if msg == WM_COMMAND {
        logln!("WM_COMMAND id {} source {} (control handle {})", w & 0xFFFF, (w >> 16) & 0xFFFF, if l == 0 { "null" } else { "set" });
    }
    if msg == WM_SYSCOMMAND {
        logln!("WM_SYSCOMMAND {:#x}", w & 0xFFF0);
    }
    // SAFETY: default processing.
    unsafe { DefWindowProcW(hwnd, msg, w, l) }
}

fn entries(t: &mut Test, label: &str, a: HACCEL) {
    let mut e = [ACCEL { f_virt: 0xEE, pad: 0xEE, key: 0xEEEE, cmd: 0xEEEE }; 10];
    set_error(0xDEAD);
    // SAFETY: e has 10 entries.
    let n = unsafe { CopyAcceleratorTableW(a, e.as_mut_ptr(), 10) };
    say!(t, "{label}: count {n}");
    for i in 0..(n.max(0) as usize).min(10) {
        say!(t, "   [{i}] flags {:#x} key {:#x} cmd {}", e[i].f_virt, e[i].key, e[i].cmd);
    }
}

fn sendkey(t: &mut Test, w: HWND, tbl: HACCEL, msg: u32, key: usize, label: &str) {
    let mut m: MSG = zeroed();
    m.hwnd = w;
    m.message = msg;
    m.wparam = key;
    m.lparam = 1;
    log_clear();
    // SAFETY: the table and window are ours.
    let r = unsafe { TranslateAcceleratorW(w, tbl, &mut m) };
    say!(t, "{label}: TranslateAcceleratorW = {r}");
    flush_log(t, "     ");
}

