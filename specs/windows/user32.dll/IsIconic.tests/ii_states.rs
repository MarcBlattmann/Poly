fn test(t: &mut Test) {
    let _cursor = CursorGuard::new();
    tag_register();
    // SAFETY: our windows throughout.
    unsafe {
        let a = mkw(b'A', 0, WS_OVERLAPPEDWINDOW, 40, 40, 300, 200, core::ptr::null_mut());
        row(t, "created hidden", a);
        ShowWindow(a, SW_SHOWNORMAL);
        row(t, "SW_SHOWNORMAL", a);
        for (name, cmd) in [
            ("SW_SHOWMINIMIZED", SW_SHOWMINIMIZED),
            ("SW_RESTORE", SW_RESTORE),
            ("SW_MINIMIZE", SW_MINIMIZE),
            ("SW_SHOWNORMAL (from minimized)", SW_SHOWNORMAL),
            ("SW_SHOWMAXIMIZED", SW_SHOWMAXIMIZED),
            ("SW_SHOWMINNOACTIVE (from maximized)", SW_SHOWMINNOACTIVE),
            ("SW_RESTORE (from minimized after maximized)", SW_RESTORE),
            ("SW_SHOWNORMAL", SW_SHOWNORMAL),
            ("SW_FORCEMINIMIZE", SW_FORCEMINIMIZE),
            ("SW_RESTORE", SW_RESTORE),
            ("SW_SHOWMAXIMIZED", SW_SHOWMAXIMIZED),
            ("SW_SHOWNORMAL", SW_SHOWNORMAL),
        ] {
            ShowWindow(a, cmd);
            row(t, name, a);
        }
        CloseWindow(a);
        row(t, "CloseWindow", a);
        ShowWindow(a, SW_RESTORE);
        let st = GetWindowLongPtrW(a, GWL_STYLE);
        SetWindowLongPtrW(a, GWL_STYLE, st | WS_MINIMIZE as isize);
        row(t, "WS_MINIMIZE set with SetWindowLongPtrW", a);
        SetWindowLongPtrW(a, GWL_STYLE, st | WS_MAXIMIZE as isize);
        row(t, "WS_MAXIMIZE set with SetWindowLongPtrW", a);
        SetWindowLongPtrW(a, GWL_STYLE, st);
        row(t, "both cleared again", a);
        ShowWindow(a, SW_HIDE);
        ShowWindow(a, SW_SHOWMAXIMIZED);
        row(t, "SW_SHOWMAXIMIZED of a hidden window", a);
        DestroyWindow(a);
        let b = mkw(b'B', 0, WS_OVERLAPPEDWINDOW | WS_MINIMIZE, 40, 40, 300, 200, core::ptr::null_mut());
        row(t, "created with WS_MINIMIZE (hidden)", b);
        ShowWindow(b, SW_SHOWNORMAL);
        row(t, "SW_SHOWNORMAL", b);
        DestroyWindow(b);
        let c = mkw(b'C', 0, WS_OVERLAPPEDWINDOW | WS_MAXIMIZE | WS_VISIBLE, 40, 40, 300, 200, core::ptr::null_mut());
        row(t, "created with WS_MAXIMIZE | WS_VISIBLE", c);
        DestroyWindow(c);
        let p = mkw(b'P', 0, WS_OVERLAPPEDWINDOW | WS_VISIBLE, 40, 40, 300, 200, core::ptr::null_mut());
        let k = mkw(b'K', 0, WS_CHILD | WS_VISIBLE | WS_MINIMIZE, 5, 5, 60, 60, p);
        row(t, "child created with WS_MINIMIZE", k);
        ShowWindow(k, SW_SHOWMAXIMIZED);
        row(t, "child ShowWindow(SW_SHOWMAXIMIZED)", k);
        ShowWindow(p, SW_MINIMIZE);
        row(t, "parent minimized: the child", k);
        row(t, "parent minimized: the parent", p);
        DestroyWindow(p);
    }
    row(t, "NULL", core::ptr::null_mut());
    row(t, "a made-up handle", 0x1234usize as HWND);
    settle(50);
}
