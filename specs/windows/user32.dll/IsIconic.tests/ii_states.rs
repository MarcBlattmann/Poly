//! IsIconic (the window is minimized: WS_MINIMIZE) and IsZoomed
//! (WS_MAXIMIZE) through ShowWindow and style changes: SW_SHOWMINIMIZED,
//! SW_MINIMIZE, SW_SHOWMINNOACTIVE, SW_FORCEMINIMIZE, SW_SHOWMAXIMIZED,
