fn row(t: &mut Test, what: &str, h: HWND) {
    set_error(0);
    // SAFETY: plain queries.
    unsafe {
        let (i, z, st) = (IsIconic(h), IsZoomed(h), GetWindowLongPtrW(h, GWL_STYLE) as u32);
        say!(
            t,
            "{what}: IsIconic={i} IsZoomed={z} WS_MINIMIZE={} WS_MAXIMIZE={} visible={} (last error {})",
            (st & WS_MINIMIZE != 0) as i32,
            (st & WS_MAXIMIZE != 0) as i32,
            IsWindowVisible(h),
            last_error()
        );
    }
}

