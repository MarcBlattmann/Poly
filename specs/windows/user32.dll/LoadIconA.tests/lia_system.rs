fn test(t: &mut Test) {
    // SAFETY: plain calls.
    unsafe { GetSystemMetrics(0) };
    let inst = instance();
    for (name, id) in [("icon application", 32512usize), ("icon hand", 32513), ("icon question", 32514), ("icon exclamation", 32515), ("icon asterisk", 32516), ("icon winlogo", 32517), ("icon shield", 32518)] {
        let a = unsafe { LoadIconA(core::ptr::null_mut(), mira(id)) };
        let w = unsafe { LoadIconW(core::ptr::null_mut(), mir(id)) };
        say!(t, "{name}: LoadIconA {} LoadIconW {} same handle {}", hwnd_kind(a), hwnd_kind(w), (a == w) as i32);
    }
    call!(t, "LoadIconA(NULL, 'application')", unsafe { LoadIconA(core::ptr::null_mut(), b"APPLICATION\0".as_ptr()) }.is_null() as i32);
    call!(t, "LoadIconA(NULL, 32519)", unsafe { LoadIconA(core::ptr::null_mut(), mira(32519)) }.is_null() as i32);
    // the executable's icons by string name
    let ia = unsafe { LoadIconA(inst, b"APPICON\0".as_ptr()) };
    say!(t, "LoadIconA('APPICON'): {} same as LoadIconW: {}", hwnd_kind(ia), (ia == unsafe { LoadIconW(inst, wz!("APPICON").as_ptr()) }) as i32);
    // a name with a character above 0x7F
    call!(t, "LoadIconA('APP\\xC9') (not a resource name)", unsafe { LoadIconA(inst, b"APP\xC9\0".as_ptr()) }.is_null() as i32);
}
