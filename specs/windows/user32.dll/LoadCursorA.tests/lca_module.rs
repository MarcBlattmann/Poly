fn test(t: &mut Test) {
    // SAFETY: plain calls.
    unsafe { GetSystemMetrics(0) };
    let inst = instance();
    say!(t, "SM_CXCURSOR {} SM_CYCURSOR {}", unsafe { GetSystemMetrics(13) }, unsafe { GetSystemMetrics(14) });
    let a = unsafe { LoadCursorA(inst, mira(600)) };
    cinfo(t, "LoadCursorA(600)", a);
    let a2 = unsafe { LoadCursorA(inst, mira(600)) };
    say!(t, "a second LoadCursorA gives the same handle: {}", (a == a2) as i32);
    let n = unsafe { LoadCursorA(inst, b"NAMEDCUR\0".as_ptr()) };
    cinfo(t, "LoadCursorA('NAMEDCUR') (one 32x32 image, hotspot 1,1)", n);
    let l = unsafe { LoadCursorA(inst, b"namedcur\0".as_ptr()) };
    say!(t, "LoadCursorA('namedcur'): {}", hwnd_kind(l));
    let z = unsafe { LoadCursorA(core::ptr::null_mut(), mira(600)) };
    say!(t, "LoadCursorA(NULL, 600): {} err={}", hwnd_kind(z), if z.is_null() { last_error() as i64 } else { -1 });
    // LoadImageA with sizes
    for (label, cx, cy, fl) in [("16x16", 16, 16, 0u32), ("32x32", 32, 32, 0), ("24x24", 24, 24, 0), ("0x0 with LR_DEFAULTSIZE", 0, 0, LR_DEFAULTSIZE), ("0x0", 0, 0, 0), ("48x48", 48, 48, 0)] {
        let h = unsafe { LoadImageA(inst, mira(600), IMAGE_CURSOR, cx, cy, fl) } as HCURSOR;
        let mut lb = Buf::<80>::new();
        let _ = write!(lb, "LoadImageA(600, IMAGE_CURSOR) {label}");
        cinfo(t, lb.as_str(), h);
        unsafe { DestroyCursor(h) };
    }
    let s1 = unsafe { LoadImageA(inst, mira(600), IMAGE_CURSOR, 0, 0, LR_SHARED | LR_DEFAULTSIZE) };
    let s2 = unsafe { LoadImageA(inst, mira(600), IMAGE_CURSOR, 0, 0, LR_SHARED | LR_DEFAULTSIZE) };
    say!(t, "LR_SHARED twice gives the same handle: {}", (s1 == s2) as i32);
    let h1 = unsafe { LoadImageA(inst, mira(600), IMAGE_CURSOR, 16, 16, 0) };
    let h2 = unsafe { LoadImageA(inst, mira(600), IMAGE_CURSOR, 16, 16, 0) };
    say!(t, "without LR_SHARED two handles: {}", (h1 != h2) as i32);
    say!(t, "DestroyCursor of an unshared cursor {} twice {}", unsafe { DestroyCursor(h1 as HCURSOR) }, unsafe { DestroyCursor(h1 as HCURSOR) });
    unsafe { DestroyCursor(h2 as HCURSOR) };
    // errors
    call!(t, "LoadCursorA absent number", unsafe { LoadCursorA(inst, mira(999)) }.is_null() as i32);
    call!(t, "LoadCursorA absent name", unsafe { LoadCursorA(inst, b"NOPE\0".as_ptr()) }.is_null() as i32);
    call!(t, "LoadCursorA of an icon group (500)", unsafe { LoadCursorA(inst, mira(500)) }.is_null() as i32);
    call!(t, "LoadCursorA of a single RT_CURSOR image number (11)", unsafe { LoadCursorA(inst, mira(11)) }.is_null() as i32);
    call!(t, "LoadCursorA of a bitmap number (400)", unsafe { LoadCursorA(inst, mira(400)) }.is_null() as i32);
    call!(t, "LoadCursorA with a made-up module", unsafe { LoadCursorA(0x1000_0000 as HINSTANCE, mira(600)) }.is_null() as i32);
    call!(t, "LoadIconA of the cursor group number", unsafe { LoadIconA(inst, mira(600)) }.is_null() as i32);
    // the system cursor keeps working beside it
    let arrow = unsafe { LoadCursorA(core::ptr::null_mut(), mira(32512)) };
    cinfo(t, "LoadCursorA(NULL, 32512)", arrow);
}
