fn cinfo(t: &mut Test, label: &str, h: HCURSOR) {
    if h.is_null() {
        say!(t, "{label}: null err={}", last_error());
        return;
    }
    let mut ii: ICONINFO = zeroed();
    // SAFETY: ii is an ICONINFO.
    let ok = unsafe { GetIconInfo(h, &mut ii) };
    let mut b: BITMAP = zeroed();
    let mut m: BITMAP = zeroed();
    // SAFETY: BITMAP structs.
    unsafe {
        GetObjectW(ii.hbm_color, core::mem::size_of::<BITMAP>() as i32, &mut b as *mut BITMAP as *mut c_void);
        GetObjectW(ii.hbm_mask, core::mem::size_of::<BITMAP>() as i32, &mut m as *mut BITMAP as *mut c_void);
    }
    let mut line = Buf::<200>::new();
    // SAFETY: the colour bitmap goes into a memory DC.
    unsafe {
        if !ii.hbm_color.is_null() {
            let dc = CreateCompatibleDC(core::ptr::null_mut());
            let old = SelectObject(dc, ii.hbm_color);
            let c = GetPixel(dc, 2, 2);
            let _ = write!(line, " pixel (2,2)=#{:02x}{:02x}{:02x}", c & 0xFF, (c >> 8) & 0xFF, (c >> 16) & 0xFF);
            SelectObject(dc, old);
            DeleteDC(dc);
        }
        DeleteObject(ii.hbm_color);
        DeleteObject(ii.hbm_mask);
    }
    say!(t, "{label}: GetIconInfo {ok} fIcon {} hotspot ({},{}) colour {}x{} bits {} mask {}x{} bits {}{}", ii.f_icon, ii.x_hotspot, ii.y_hotspot, b.width, b.height, b.bits_pixel, m.width, m.height, m.bits_pixel, line.as_str());
}

