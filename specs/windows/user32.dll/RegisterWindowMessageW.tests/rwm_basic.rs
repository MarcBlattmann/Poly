static SEEN: Global<u32> = Global::new(0);
static OTHER: Global<u32> = Global::new(0);

unsafe extern "system" fn proc_m(hwnd: HWND, msg: u32, w: WPARAM, l: LPARAM) -> LRESULT {
    if msg >= 0xC000 {
        *SEEN.get() = msg;
        return 77;
    }
    // SAFETY: the default handling of the message just received.
    unsafe { DefWindowProcW(hwnd, msg, w, l) }
}

unsafe extern "system" fn thread_main(_p: *mut c_void) -> u32 {
    // SAFETY: a plain call with a static name.
    unsafe { *OTHER.get() = RegisterWindowMessageW(wz!("Poly_Msg_A").as_ptr()) };
    0
}

poly_wtest::main!(test);

fn test(t: &mut Test) {
    let _cursor = CursorGuard::new();
    t.check("registered", register(wz!("MsgWin"), Some(proc_m), 0, 0, core::ptr::null_mut()) != 0, 0);
    // SAFETY: our window and thread throughout.
    unsafe {
        set_error(0);
        let a = RegisterWindowMessageW(wz!("Poly_Msg_A").as_ptr());
        say!(t, "a new name: in the range 0xC000..0xFFFF: {} (last error {})", (0xC000..=0xFFFF).contains(&a) as i32, last_error());
        say!(t, "the same name again: same id {}", (RegisterWindowMessageW(wz!("Poly_Msg_A").as_ptr()) == a) as i32);
        say!(t, "upper case: same id {}", (RegisterWindowMessageW(wz!("POLY_MSG_A").as_ptr()) == a) as i32);
        let b = RegisterWindowMessageW(wz!("Poly_Msg_B").as_ptr());
        say!(t, "another name: different id {} in range {}", (b != a) as i32, (0xC000..=0xFFFF).contains(&b) as i32);
        let th = CreateThread(core::ptr::null_mut(), 0, thread_main, core::ptr::null_mut(), 0, core::ptr::null_mut());
        WaitForSingleObject(th, 5000);
        CloseHandle(th);
        say!(t, "from another thread: same id {}", (*OTHER.get() == a) as i32);
        let task = RegisterWindowMessageW(wz!("TaskbarCreated").as_ptr());
        say!(t, "TaskbarCreated: in range {} twice the same {}", (0xC000..=0xFFFF).contains(&task) as i32, (RegisterWindowMessageW(wz!("TaskbarCreated").as_ptr()) == task) as i32);
        for (label, n) in [("255 characters", 255usize), ("256 characters", 256), ("300 characters", 300)] {
            let mut s = [b'q' as u16; 302];
            s[n] = 0;
            set_error(0);
            let r = RegisterWindowMessageW(s.as_ptr());
            say!(t, "{label}: id in range {} (last error {})", (0xC000..=0xFFFF).contains(&r) as i32, last_error());
        }
        set_error(0);
        let r = RegisterWindowMessageW(wz!("").as_ptr());
        say!(t, "the empty string: {r} (last error {})", last_error());
        set_error(0);
        let r = RegisterWindowMessageW(core::ptr::null());
        say!(t, "NULL: {r} (last error {})", last_error());
        set_error(0);
        let r = RegisterWindowMessageW(wz!("#1234").as_ptr());
        say!(t, "\"#1234\": in range {} (last error {})", (0xC000..=0xFFFF).contains(&r) as i32, last_error());
        let w = create(0, wz!("MsgWin"), &[], WS_POPUP, 0, 0, 10, 10, core::ptr::null_mut(), 0);
        let res = SendMessageW(w, a, 1, 2);
        say!(t, "SendMessageW with the id: result {res}, the window saw the id {}", (*SEEN.get() == a) as i32);
        let ok = PostMessageW(w, b, 0, 0);
        settle(50);
        say!(t, "PostMessageW with another id: {ok}, the window saw it: {}", (*SEEN.get() == b) as i32);
        DestroyWindow(w);
    }
    settle(50);
}
