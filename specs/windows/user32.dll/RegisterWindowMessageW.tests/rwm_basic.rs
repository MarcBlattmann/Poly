//! RegisterWindowMessageW (1 call in a Chrome run, "TaskbarCreated"): the
//! message id is in the range 0xC000..0xFFFF; the same string gives the same
//! id on every call, also from another thread, and the same as
//! RegisterClipboardFormatW of a string would give? (they share the atom
//! table: printed as observed); different strings give different ids;
//! strings are compared case-insensitively (an id for "Poly_Msg" equals
//! the id for "POLY_MSG"); a string of 255 characters is fine and one of 256
//! fails with ERROR_INVALID_PARAMETER? (printed as observed); the empty
//! string and NULL fail (0 with the last error); a numeric-looking string
//! "#1234"; the id works: a message registered under the name is delivered
//! to a window with that id; ids registered earlier stay valid; ids are
//! allocated in increasing order within a process? (printed as the relation
//! between two new ids); the system's own message "TaskbarCreated" can be
//! registered by anyone and gives the same id as in another registration
//! within the process.
#![no_std]
#![no_main]
#![allow(dead_code, non_camel_case_types, clippy::all)]

