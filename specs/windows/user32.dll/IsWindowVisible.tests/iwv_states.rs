fn rep(t: &mut Test, what: &str, h: HWND) {
    set_error(0);
    // SAFETY: plain queries.
    let (v, st) = unsafe { (IsWindowVisible(h), GetWindowLongPtrW(h, GWL_STYLE) as u32) };
    say!(t, "{what}: IsWindowVisible={v} WS_VISIBLE={} last error {}", (st & WS_VISIBLE != 0) as i32, last_error());
}

