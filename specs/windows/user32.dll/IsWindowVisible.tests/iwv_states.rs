fn test(t: &mut Test) {
    let _cursor = CursorGuard::new();
    tag_register();
    let a = mkw(b'A', 0, WS_OVERLAPPEDWINDOW, 40, 40, 300, 200, core::ptr::null_mut());
    rep(t, "created hidden", a);
    // SAFETY: our window throughout.
    unsafe {
        ShowWindow(a, SW_SHOWNORMAL);
        rep(t, "SW_SHOWNORMAL", a);
        ShowWindow(a, SW_SHOWMINIMIZED);
        rep(t, "SW_SHOWMINIMIZED", a);
        say!(t, "  IsIconic={}", IsIconic(a));
        ShowWindow(a, SW_RESTORE);
        rep(t, "SW_RESTORE", a);
        ShowWindow(a, SW_SHOWMAXIMIZED);
        rep(t, "SW_SHOWMAXIMIZED", a);
        ShowWindow(a, SW_RESTORE);
        ShowWindow(a, SW_HIDE);
        rep(t, "SW_HIDE", a);
        SetWindowPos(a, core::ptr::null_mut(), 0, 0, 0, 0, SWP_NOMOVE | SWP_NOSIZE | SWP_NOZORDER | SWP_NOACTIVATE | SWP_SHOWWINDOW);
        rep(t, "SetWindowPos SWP_SHOWWINDOW", a);
        SetWindowPos(a, core::ptr::null_mut(), 0, 0, 0, 0, SWP_NOMOVE | SWP_NOSIZE | SWP_NOZORDER | SWP_NOACTIVATE | SWP_HIDEWINDOW);
        rep(t, "SetWindowPos SWP_HIDEWINDOW", a);
        let st = GetWindowLongPtrW(a, GWL_STYLE);
        SetWindowLongPtrW(a, GWL_STYLE, st | WS_VISIBLE as isize);
        rep(t, "WS_VISIBLE set with SetWindowLongPtrW", a);
        SetWindowLongPtrW(a, GWL_STYLE, st);
        rep(t, "WS_VISIBLE cleared with SetWindowLongPtrW", a);
        ShowWindow(a, SW_SHOWNA);
        rep(t, "SW_SHOWNA", a);
        ShowWindow(a, SW_SHOWMINNOACTIVE);
        rep(t, "SW_SHOWMINNOACTIVE", a);
        DestroyWindow(a);
    }
    rep(t, "destroyed", a);
    let b = mkw(b'B', 0, WS_OVERLAPPEDWINDOW | WS_VISIBLE, 40, 40, 300, 200, core::ptr::null_mut());
    rep(t, "created with WS_VISIBLE", b);
    // SAFETY: our window.
    unsafe { DestroyWindow(b) };
    rep(t, "NULL", core::ptr::null_mut());
    rep(t, "a made-up handle", 0x1234usize as HWND);
    // SAFETY: plain query.
    let d = unsafe { GetDesktopWindow() };
    rep(t, "the desktop window", d);
    settle(50);
}
