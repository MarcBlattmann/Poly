//! IsWindowVisible on a top-level window through its life: created hidden,
//! shown (SW_SHOWNORMAL), minimized (still visible: WS_VISIBLE and the
//! parent chain count, not whether the window is on screen), maximized,
//! restored, hidden with SW_HIDE, shown with SetWindowPos(SWP_SHOWWINDOW)
//! and hidden with SWP_HIDEWINDOW, set and cleared through WS_VISIBLE with
//! SetWindowLongPtrW(GWL_STYLE) (the bit alone does not hide or show: the
//! call only reads the bit), created with WS_VISIBLE, destroyed. The
//! results of the call and the WS_VISIBLE bit are printed side by side.
