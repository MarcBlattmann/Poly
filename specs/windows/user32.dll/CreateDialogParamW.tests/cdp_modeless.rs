unsafe extern "system" fn dlg_proc(hwnd: HWND, msg: u32, _w: WPARAM, l: LPARAM) -> isize {
    match msg {
        WM_INITDIALOG => {
            logln!("WM_INITDIALOG param {}", l);
            return 1;
        }
        WM_DESTROY => logln!("WM_DESTROY"),
        WM_NCDESTROY => logln!("WM_NCDESTROY"),
        WM_CLOSE => logln!("WM_CLOSE"),
        _ => {}
    }
    let _ = hwnd;
    0
}

