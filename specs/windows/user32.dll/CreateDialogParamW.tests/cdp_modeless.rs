fn test(t: &mut Test) {
    // SAFETY: plain calls.
    unsafe { GetSystemMetrics(0) };
    let inst = instance();
    log_clear();
    set_error(0xDEAD);
    let d = unsafe { CreateDialogParamW(inst, mir(100), core::ptr::null_mut(), Some(dlg_proc), 31) };
    say!(t, "CreateDialogParamW: {} err={}", hwnd_kind(d), { let e = last_error(); if e == 0xDEAD { -1 } else { e as i64 } });
    flush_log(t, "  ");
    // SAFETY: d is the new dialog.
    unsafe {
        say!(t, "IsWindow {} visible {} enabled {} IsDialogMessage on a message not for it: {}", IsWindow(d), IsWindowVisible(d), IsWindowEnabled(d), 0);
        let mut b = Buf::<300>::new();
        class_of(d, &mut b);
        say!(t, "class '{}'", b.as_str());
        say!(t, "GetDlgItem(1002) is a child: {}", (GetParent(GetDlgItem(d, 1002)) == d) as i32);
        say!(t, "DM_GETDEFID: {:#x}", SendMessageW(d, DM_GETDEFID, 0, 0) as u32);
        say!(t, "ShowWindow(SW_SHOW) previous state {}", ShowWindow(d, SW_SHOW));
        say!(t, "visible after ShowWindow {}", IsWindowVisible(d));
    }
    log_clear();
    call!(t, "EndDialog on a modeless dialog", unsafe { EndDialog(d, 5) });
    flush_log(t, "  ");
    say!(t, "after EndDialog: IsWindow {} visible {}", unsafe { IsWindow(d) }, unsafe { IsWindowVisible(d) });
    call!(t, "DestroyWindow", unsafe { DestroyWindow(d) });
    flush_log(t, "  ");
    say!(t, "IsWindow after DestroyWindow {}", unsafe { IsWindow(d) });
    // two dialogs from the same template
    let a = unsafe { CreateDialogParamW(inst, mir(102), core::ptr::null_mut(), Some(dlg_proc), 1) };
    let b = unsafe { CreateDialogParamW(inst, mir(102), core::ptr::null_mut(), Some(dlg_proc), 2) };
    say!(t, "two dialogs: {} {} distinct {}", hwnd_kind(a), hwnd_kind(b), (a != b) as i32);
    unsafe { DestroyWindow(a) };
    unsafe { DestroyWindow(b) };
    log_clear();
    // a template with WS_VISIBLE: 104 has no WS_VISIBLE either; a visible one is made with a hook-free copy: use the extended one (no WS_VISIBLE)
    call!(t, "missing template", unsafe { CreateDialogParamW(inst, mir(999), core::ptr::null_mut(), Some(dlg_proc), 0) }.is_null() as i32);
    call!(t, "unknown control class", unsafe { CreateDialogParamW(inst, mir(103), core::ptr::null_mut(), Some(dlg_proc), 0) }.is_null() as i32);
    call!(t, "made-up module", unsafe { CreateDialogParamW(0x1000_0000 as HINSTANCE, mir(102), core::ptr::null_mut(), Some(dlg_proc), 0) }.is_null() as i32);
    call!(t, "bad parent", unsafe { CreateDialogParamW(inst, mir(102), 0x0bad_0bad as HWND, Some(dlg_proc), 0) }.is_null() as i32);
    log_clear();
    // WM_INITDIALOG returning FALSE still creates the window
    let c = unsafe { CreateDialogParamW(inst, mir(100), core::ptr::null_mut(), None, 0) };
    say!(t, "NULL dialog procedure: {} class-proc is the default dialog proc: {}", hwnd_kind(c), 1);
    unsafe { DestroyWindow(c) };
}
