fn describe(t: &mut Test, label: &str, bmp: HBITMAP) {
    if bmp.is_null() {
        say!(t, "{label}: null err={}", last_error());
        return;
    }
    let mut b: BITMAP = zeroed();
    // SAFETY: b is a BITMAP.
    let n = unsafe { GetObjectW(bmp, core::mem::size_of::<BITMAP>() as i32, &mut b as *mut BITMAP as *mut c_void) };
    say!(t, "{label}: GetObject {n} width {} height {} planes {} bits {} width_bytes {} has bits pointer {}", b.width, b.height, b.planes, b.bits_pixel, b.width_bytes, (b.bits != 0) as i32);
}

fn pixels(t: &mut Test, label: &str, bmp: HBITMAP, pts: &[(i32, i32)]) {
    // SAFETY: a memory DC of the screen, the bitmap selected into it.
    unsafe {
        let dc = CreateCompatibleDC(core::ptr::null_mut());
        let old = SelectObject(dc, bmp);
        let mut line = Buf::<300>::new();
        for &(x, y) in pts {
            let c = GetPixel(dc, x, y);
            let _ = write!(line, " ({x},{y})=#{:02x}{:02x}{:02x}", c & 0xFF, (c >> 8) & 0xFF, (c >> 16) & 0xFF);
        }
        say!(t, "{label}: pixels (r,g,b){}", line.as_str());
        SelectObject(dc, old);
        DeleteDC(dc);
    }
}

