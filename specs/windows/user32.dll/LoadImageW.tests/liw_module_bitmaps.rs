fn test(t: &mut Test) {
    // SAFETY: plain calls.
    unsafe { GetSystemMetrics(0) };
    let inst = instance();
    let b = unsafe { LoadBitmapW(inst, mir(400)) };
    describe(t, "LoadBitmapW(400)", b);
    pixels(t, "LoadBitmapW(400)", b, &[(0, 0), (1, 0), (0, 1), (3, 2), (2, 2)]);
    say!(t, "DeleteObject {}", unsafe { DeleteObject(b) });
    let n = unsafe { LoadBitmapW(inst, wz!("NAMEDBMP").as_ptr()) };
    describe(t, "LoadBitmapW('NAMEDBMP')", n);
    pixels(t, "LoadBitmapW('NAMEDBMP')", n, &[(0, 0), (7, 1)]);
    unsafe { DeleteObject(n) };
    let l = unsafe { LoadBitmapW(inst, wz!("namedbmp").as_ptr()) };
    say!(t, "LoadBitmapW('namedbmp'): {}", hwnd_kind(l));
    unsafe { DeleteObject(l) };
    // two loads give two bitmaps
    let a1 = unsafe { LoadBitmapW(inst, mir(400)) };
    let a2 = unsafe { LoadBitmapW(inst, mir(400)) };
    say!(t, "two loads are two handles: {}", (a1 != a2) as i32);
    unsafe { DeleteObject(a1) };
    unsafe { DeleteObject(a2) };
    // LoadImageW
    let i = unsafe { LoadImageW(inst, mir(400), IMAGE_BITMAP, 0, 0, 0) } as HBITMAP;
    describe(t, "LoadImageW bitmap, no flags", i);
    unsafe { DeleteObject(i) };
    let d = unsafe { LoadImageW(inst, mir(400), IMAGE_BITMAP, 0, 0, LR_CREATEDIBSECTION) } as HBITMAP;
    describe(t, "LoadImageW bitmap, LR_CREATEDIBSECTION", d);
    pixels(t, "  DIB section", d, &[(0, 0), (1, 0)]);
    unsafe { DeleteObject(d) };
    let s = unsafe { LoadImageW(inst, mir(400), IMAGE_BITMAP, 8, 6, 0) } as HBITMAP;
    describe(t, "LoadImageW bitmap stretched to 8x6", s);
    unsafe { DeleteObject(s) };
    let m = unsafe { LoadImageW(inst, mir(400), IMAGE_BITMAP, 0, 0, LR_MONOCHROME) } as HBITMAP;
    describe(t, "LoadImageW bitmap, LR_MONOCHROME", m);
    unsafe { DeleteObject(m) };
    // errors
    call!(t, "absent number", unsafe { LoadBitmapW(inst, mir(999)) }.is_null() as i32);
    call!(t, "absent name", unsafe { LoadBitmapW(inst, wz!("NOPE").as_ptr()) }.is_null() as i32);
    call!(t, "an icon resource number", unsafe { LoadBitmapW(inst, mir(500)) }.is_null() as i32);
    call!(t, "made-up module", unsafe { LoadBitmapW(0x1000_0000 as HINSTANCE, mir(400)) }.is_null() as i32);
    call!(t, "NULL module (the executable)", unsafe { LoadBitmapW(core::ptr::null_mut(), mir(400)) }.is_null() as i32);
    call!(t, "LoadImageW absent", unsafe { LoadImageW(inst, mir(999), IMAGE_BITMAP, 0, 0, 0) }.is_null() as i32);
    call!(t, "LoadImageW unknown type 7", unsafe { LoadImageW(inst, mir(400), 7, 0, 0, 0) }.is_null() as i32);
}
