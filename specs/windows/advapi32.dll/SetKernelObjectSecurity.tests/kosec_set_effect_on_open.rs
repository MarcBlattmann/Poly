fn open(t: &mut Test, label: &str, name: &[u16; 256], access: u32) {
    // SAFETY: NUL-terminated name.
    let h = unsafe { OpenEventW(access, FALSE, name.as_ptr()) };
    if h.is_null() {
        sdsay!(t, "{label}: open {access:#x} failed err={}", gle());
    } else {
        sdsay!(t, "{label}: open {access:#x} ok granted={:#x}", granted_access(h));
        // SAFETY: closing the handle.
        unsafe { CloseHandle(h) };
    }
}

fn test(t: &mut Test) {
    let mut name_text = Buf::<80>::new();
    // SAFETY: reads the process id.
    let _ = write!(name_text, "PolySecSdEvent{}", unsafe { GetCurrentProcessId() });
    let name = wide(name_text.as_str());
    // SAFETY: no attributes; NUL-terminated name.
    let ev = unsafe { CreateEventW(core::ptr::null(), TRUE, FALSE, name.as_ptr()) };
    sdsay!(t, "created: {}", !ev.is_null());
    for access in
        [SYNCHRONIZE, EVENT_MODIFY_STATE, READ_CONTROL, WRITE_DAC, WRITE_OWNER, EVENT_ALL_ACCESS, MAXIMUM_ALLOWED]
    {
        open(t, "default DACL", &name, access);
    }
    for (title, sddl) in [
        ("Everyone SYNCHRONIZE only", "D:(A;;0x100000;;;WD)"),
        ("deny Everyone MODIFY_STATE, then allow Everyone all", "D:(D;;0x2;;;WD)(A;;0x1f0003;;;WD)"),
        ("empty DACL", "D:"),
        ("NULL DACL", "D:NO_ACCESS_CONTROL"),
        ("Everyone all access", "D:(A;;0x1f0003;;;WD)"),
    ] {
        let sd = sd_from(sddl);
        sd_sko_say(t, title, ev, 4, sd.ptr());
        sd_kernel_text(t, "  dacl", ev, 4);
        for access in
            [SYNCHRONIZE, EVENT_MODIFY_STATE, READ_CONTROL, WRITE_DAC, WRITE_OWNER, EVENT_ALL_ACCESS, MAXIMUM_ALLOWED]
        {
            open(t, "  after", &name, access);
        }
    }
    // SAFETY: closing the handle.
    unsafe { CloseHandle(ev) };
}
