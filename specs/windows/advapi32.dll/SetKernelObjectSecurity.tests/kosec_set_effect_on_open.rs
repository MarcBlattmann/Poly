//! SetKernelObjectSecurity changes what OpenEventW grants: a named event (PolySec prefix) whose DACL is
//! replaced by an allow ACE for Everyone, a deny ACE, an empty DACL (owner rights remain), a NULL DACL;
//! the access mask the new handles get. (ambient: the caller is the owner of the event)
#![no_std]
#![no_main]
#![allow(dead_code, non_camel_case_types, non_upper_case_globals, non_snake_case, clippy::all)]

