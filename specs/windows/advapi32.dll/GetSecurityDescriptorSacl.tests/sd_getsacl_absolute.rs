fn test(t: &mut Test) {
    let mut a = SdAbs::new();
    sd_say_acl(t, "absent", &sd_get_sacl(a.cp()), a.cp(), 40);
    // SAFETY: valid descriptor.
    unsafe { SetSecurityDescriptorSacl(a.p(), TRUE, core::ptr::null(), FALSE) };
    sd_say_acl(t, "NULL", &sd_get_sacl(a.cp()), a.cp(), 40);
    a.set_sacl(&[]);
    let g = sd_get_sacl(a.cp());
    sd_say_acl(t, "empty", &g, a.cp(), 40);
    sdsay!(t, "  same pointer as passed: {}", g.acl as usize == a.sacl.b.as_ptr() as usize);
    a.set_sacl(&[(2, 0xC0, 0x1F01FF, "S-1-1-0"), (0x11, 0, SYSTEM_MANDATORY_LABEL_NO_WRITE_UP, "S-1-16-4096")]);
    let g = sd_get_sacl(a.cp());
    sd_say_acl(t, "audit and label ACEs", &g, a.cp(), 40);
    sd_acl_show(t, "  acl", g.acl);
    // SAFETY: valid descriptor and ACL.
    unsafe { SetSecurityDescriptorSacl(a.p(), TRUE, a.sacl.p(), TRUE) };
    sd_say_acl(t, "defaulted", &sd_get_sacl(a.cp()), a.cp(), 40);
    // SAFETY: valid descriptor.
    unsafe { SetSecurityDescriptorSacl(a.p(), FALSE, core::ptr::null(), FALSE) };
    sd_say_acl(t, "present cleared again", &sd_get_sacl(a.cp()), a.cp(), 40);
    let mut b = SdAbs::new();
    b.sd.b[2] |= 0x10;
    sd_say_acl(t, "SACL_PRESENT by hand, NULL slot", &sd_get_sacl(b.cp()), b.cp(), 40);
    let mut c = SdAbs::new();
    c.set_sacl(&[(2, 0, 0x1F01FF, "S-1-1-0")]);
    c.sd.b[2] &= !0x10;
    sd_say_acl(t, "slot set, SACL_PRESENT cleared by hand", &sd_get_sacl(c.cp()), c.cp(), 40);
}
