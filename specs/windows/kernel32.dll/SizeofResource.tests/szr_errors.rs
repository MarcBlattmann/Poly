const LOAD_AS_DATAFILE: u32 = 0x2;
const LOAD_AS_IMAGE_RESOURCE: u32 = 0x20;
const RT_RCDATA: u16 = 10;
const RT_STRING: u16 = 6;
const RT_ICON: u16 = 3;
