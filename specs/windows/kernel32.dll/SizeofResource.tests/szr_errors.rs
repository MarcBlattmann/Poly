fn test(t: &mut Test) {
    let h = open_pe(t, "datafile", LOAD_AS_DATAFILE);
    if h.is_null() {
        return;
    }
    let r = fr(t, h, "datafile", Rid::N(RT_RCDATA), Rid::N(100), None);
    // SAFETY: handles of this test's module and resource; NULL arguments are what is being tried.
    unsafe {
        mark_error();
        let g = LoadResource(h, core::ptr::null_mut());
        say!(
            t,
            "LoadResource(module, NULL) -> {}, error {}",
            if g.is_null() { "NULL" } else { "a handle" },
            err_text().as_str()
        );
        mark_error();
        let g = LoadResource(core::ptr::null_mut(), core::ptr::null_mut());
        say!(
            t,
            "LoadResource(NULL, NULL) -> {}, error {}",
            if g.is_null() { "NULL" } else { "a handle" },
            err_text().as_str()
        );
        mark_error();
        let p = LockResource(core::ptr::null_mut());
        say!(
            t,
            "LockResource(NULL) -> {}, error {}",
            if p.is_null() { "NULL" } else { "a pointer" },
            err_text().as_str()
        );
        mark_error();
        let n = SizeofResource(h, core::ptr::null_mut());
        say!(t, "SizeofResource(module, NULL) -> {n}, error {}", err_text().as_str());
        mark_error();
        let n = SizeofResource(core::ptr::null_mut(), core::ptr::null_mut());
        say!(t, "SizeofResource(NULL, NULL) -> {n}, error {}", err_text().as_str());
        // The module that the resource was found in is not the one it is loaded from: the other is the exe.
        let me = GetModuleHandleW(core::ptr::null());
        mark_error();
        let n = SizeofResource(me, r);
        say!(
            t,
            "SizeofResource(this exe, handle of the DLL's resource) -> {}, error {}",
            if n == 0 { "0" } else { "a size" },
            err_text().as_str()
        );
    }
    close_pe(h);
}
