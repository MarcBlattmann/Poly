//! The desktop's Windows GUI test apps, built on any host (ADR 0133).
//!
//! `cargo xtask pipeline win build` builds the Windows test programs of
//! `tests/windows/` (ADR 0075), but the pipeline tool needs a Unix host.
//! The desktop image needs only one or two of them, the GUI ones of
//! `desktop-win32` (ADR 0131), on every host. So this builds them the same
//! way: a generated Cargo package with a binary per program on
//! `tests/windows/support`, for `x86_64-pc-windows-msvc` with `core` built
//! from `rust-src` and linked by `rust-lld` as `lld-link`, with no default
//! libraries and the same flags (`tools/pipeline/src/windows.rs`:
//! `cargo_toml`, `rustflags`; keep the two the same). No C toolchain and
//! no Windows SDK are needed.

use crate::{Result, root};
use std::path::{Path, PathBuf};

/// Where the package is generated and built.
fn dir() -> PathBuf {
    root().join("target").join("winapp")
}

/// `s` as a TOML basic string.
fn toml_str(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The generated package's manifest: one binary per `(name, source)`.
fn cargo_toml(support: &Path, programs: &[(&str, PathBuf)]) -> String {
    let mut s = String::from(
        "# Generated by cargo xtask (winapp.rs, ADR 0133); do not edit.\n[workspace]\n\n[package]\n\
         name = \"poly-desktop-winapps\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\
         autobins = false\nautoexamples = false\nautotests = false\nautobenches = false\n\n[dependencies]\n",
    );
    s.push_str(&format!("poly-wtest = {{ path = {} }}\n", toml_str(&support.to_string_lossy())));
    for (name, path) in programs {
        s.push_str(&format!(
            "\n[[bin]]\nname = {}\npath = {}\ntest = false\nbench = false\n",
            toml_str(name),
            toml_str(&path.to_string_lossy())
        ));
    }
    s.push_str(
        "\n[profile.release]\npanic = \"abort\"\nopt-level = \"s\"\ncodegen-units = 1\ndebug = false\nlto = true\n\
         \n[profile.dev]\npanic = \"abort\"\n",
    );
    s
}

/// The compiler's flags (as the pipeline's).
fn rustflags(sysroot: &Path) -> Vec<String> {
    let mut f: Vec<String> = [
        "-Clinker=rust-lld",
        "-Clinker-flavor=lld-link",
        "-Clink-arg=/NODEFAULTLIB",
        "-Clink-arg=/ENTRY:mainCRTStartup",
        "-Clink-arg=/SUBSYSTEM:CONSOLE",
        "-Clink-arg=/Brepro",
        "-Clink-arg=/DEBUG:NONE",
        "-Cdebuginfo=0",
    ]
    .map(String::from)
    .to_vec();
    f.push(format!("--remap-path-prefix={}=/poly", root().display()));
    f.push(format!("--remap-path-prefix={}=/rust", sysroot.display()));
    f
}

/// Build the test programs `names` (`tests/windows/<name>.rs`); returns
/// each one's executable.
pub fn build(names: &[&str]) -> Result<Vec<(String, Vec<u8>)>> {
    const TARGET: &str = "x86_64-pc-windows-msvc";
    let out = std::process::Command::new("rustc").args(["--print", "sysroot"]).output();
    let sysroot =
        PathBuf::from(String::from_utf8_lossy(&out.map_err(|e| format!("rustc: {e}"))?.stdout).trim().to_string());
    let vendor = crate::ntdll::vendor_dir()?;
    let programs: Vec<(&str, PathBuf)> =
        names.iter().map(|n| (*n, root().join("tests/windows").join(format!("{n}.rs")))).collect();
    let package = dir().join("build");
    std::fs::create_dir_all(&package).map_err(|e| format!("{}: {e}", package.display()))?;
    let manifest = package.join("Cargo.toml");
    let text = cargo_toml(&root().join("tests/windows/support"), &programs);
    // Rewritten only when it changes, so cargo's build stays fresh.
    if std::fs::read_to_string(&manifest).ok().as_deref() != Some(text.as_str()) {
        std::fs::write(&manifest, text).map_err(|e| format!("{}: {e}", manifest.display()))?;
    }
    let target_dir = dir().join("target");
    let mut cmd = crate::cargo();
    cmd.current_dir(root())
        .env("RUSTC_BOOTSTRAP", "1")
        .env("CARGO_INCREMENTAL", "0")
        .env("CARGO_ENCODED_RUSTFLAGS", rustflags(&sysroot).join("\u{1f}"))
        .env_remove("RUSTFLAGS")
        .args(["build", "--release", "--manifest-path"])
        .arg(&manifest)
        .args(["-Zbuild-std=core,compiler_builtins", "-Zbuild-std-features=compiler-builtins-mem"])
        .args(["--target", TARGET, "--target-dir"])
        .arg(&target_dir)
        .args(["--offline", "--config", "source.crates-io.replace-with=\"rustsrc\"", "--config"])
        .arg(format!("source.rustsrc.directory={}", toml_str(&vendor.to_string_lossy())));
    crate::step(&format!("build the Windows test apps ({})", names.join(", ")), &mut cmd)?;
    names
        .iter()
        .map(|n| {
            let exe = target_dir.join(TARGET).join("release").join(format!("{n}.exe"));
            let data = std::fs::read(&exe).map_err(|e| format!("{}: {e}", exe.display()))?;
            if !data.starts_with(b"MZ") {
                return Err(format!("{}: not a Windows executable", exe.display()));
            }
            Ok((n.to_string(), data))
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_manifest_has_a_binary_per_program() {
        let m = cargo_toml(Path::new("C:\\poly\\support"), &[("win_gui_fill", PathBuf::from("/p/win_gui_fill.rs"))]);
        assert!(m.contains("poly-wtest = { path = \"C:\\\\poly\\\\support\" }"), "{m}");
        assert!(m.contains("[[bin]]\nname = \"win_gui_fill\"\npath = \"/p/win_gui_fill.rs\""), "{m}");
        assert!(m.contains("panic = \"abort\""));
        assert_eq!(toml_str("a\"b\u{1}"), "\"a\\\"b\\u0001\"");
    }
}
