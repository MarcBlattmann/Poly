//! Generates the progress section of the README from coverage.json.

use crate::model::{Coverage, Entry, Layer, Os, Status};
use std::collections::BTreeMap;
use std::fmt::Write as _;

pub const BEGIN: &str = "<!-- coverage:begin -->";
pub const END: &str = "<!-- coverage:end -->";

const BAR_WIDTH: usize = 16;

/// Shown before usage weights exist: the modules almost every app loads.
const CORE_COMPONENTS: [&str; 12] = [
    "ntdll.dll",
    "kernelbase.dll",
    "kernel32.dll",
    "user32.dll",
    "gdi32.dll",
    "advapi32.dll",
    "ole32.dll",
    "shell32.dll",
    "comctl32.dll",
    "ucrtbase.dll",
    "d3d11.dll",
    "dxgi.dll",
];

#[derive(Default)]
struct Tally {
    total: u64,
    by_status: BTreeMap<Status, u64>,
    weight: f64,
    weight_green: f64,
}

impl Tally {
    fn add(&mut self, e: &Entry) {
        self.total += 1;
        *self.by_status.entry(e.status).or_default() += 1;
        self.weight += e.weight;
        if e.status == Status::Green {
            self.weight_green += e.weight;
        }
    }

    fn count(&self, s: Status) -> u64 {
        self.by_status.get(&s).copied().unwrap_or(0)
    }

    fn raw(&self) -> Option<f64> {
        (self.total > 0).then(|| self.count(Status::Green) as f64 / self.total as f64 * 100.0)
    }

    fn weighted(&self) -> Option<f64> {
        (self.weight > 0.0).then(|| self.weight_green / self.weight * 100.0)
    }
}

fn bar(pct: f64) -> String {
    let filled = ((pct / 100.0) * BAR_WIDTH as f64).round() as usize;
    format!("{}{}", "█".repeat(filled.min(BAR_WIDTH)), "░".repeat(BAR_WIDTH - filled.min(BAR_WIDTH)))
}

fn pct(p: Option<f64>) -> String {
    p.map_or_else(|| "n/a".to_string(), |p| format!("{p:.1}%"))
}

fn layer_title(os: Os, layer: Layer) -> &'static str {
    match (os, layer) {
        (Os::Linux, Layer::Syscall) => "syscalls",
        (Os::Windows, Layer::Syscall) => "NT + win32k system services",
        (Os::Macos, Layer::Syscall) => "BSD syscalls + Mach traps",
        (Os::Linux, Layer::Api) => "user-mode API",
        (Os::Windows, Layer::Api) => "user-mode DLL exports",
        (Os::Macos, Layer::Api) => "framework API",
    }
}

pub fn render(c: &Coverage) -> String {
    let mut per_os: BTreeMap<Os, Tally> = BTreeMap::new();
    let mut per_layer: BTreeMap<(Os, Layer), Tally> = BTreeMap::new();
    let mut per_component: BTreeMap<(Os, Layer, &str), Tally> = BTreeMap::new();
    for e in &c.entries {
        per_os.entry(e.os).or_default().add(e);
        per_layer.entry((e.os, e.layer)).or_default().add(e);
        per_component.entry((e.os, e.layer, e.component.as_str())).or_default().add(e);
    }

    let mut out = String::new();
    out.push_str(BEGIN);
    out.push_str("\n<!-- Generated by `cargo xtask coverage readme` from coverage/coverage.json. Do not edit. -->\n\n");

    out.push_str("```\n");
    for os in Os::ALL {
        let t = per_os.get(&os);
        let raw = t.and_then(Tally::raw);
        let traces = c.traces.get(&os).copied().unwrap_or_default();
        let _ = writeln!(
            out,
            "{:<9} {} {:>6}  (app-weighted: {}, traces passing: {}/{})",
            os.title(),
            bar(raw.unwrap_or(0.0)),
            pct(raw),
            pct(t.and_then(Tally::weighted)),
            traces.passing,
            traces.total
        );
    }
    out.push_str("```\n\n");

    out.push_str("| OS | Layer | Entries | Green | Stub | Claimed | Missing | Blocked |\n");
    out.push_str("|---|---|---:|---:|---:|---:|---:|---:|\n");
    for os in Os::ALL {
        for layer in [Layer::Syscall, Layer::Api] {
            let title = layer_title(os, layer);
            match per_layer.get(&(os, layer)) {
                Some(t) => {
                    let _ = writeln!(
                        out,
                        "| {} | {title} | {} | {} | {} | {} | {} | {} |",
                        os.title(),
                        t.total,
                        t.count(Status::Green),
                        t.count(Status::Stub),
                        t.count(Status::Claimed),
                        t.count(Status::Missing),
                        t.count(Status::BlockedByDesign)
                    );
                }
                None => {
                    let note = if (os, layer) == (Os::Linux, Layer::Api) {
                        "runs unchanged (glibc, Mesa, GTK, Qt)"
                    } else {
                        "not seeded yet"
                    };
                    let _ = writeln!(out, "| {} | {title} | {note} | | | | | |", os.title());
                }
            }
        }
    }

    // Until the call tracer produces weights, show the core components;
    // after that, the most-used ones.
    let mut comps: Vec<_> = per_component.iter().filter(|((_, l, _), _)| *l == Layer::Api).collect();
    let weighted = comps.iter().any(|(_, t)| t.weight > 0.0);
    if weighted {
        comps.sort_by(|a, b| b.1.weight.total_cmp(&a.1.weight).then(a.0.cmp(b.0)));
    } else {
        comps.retain(|((_, _, name), _)| CORE_COMPONENTS.contains(name));
        comps.sort_by_key(|((_, _, name), _)| CORE_COMPONENTS.iter().position(|c| c == name));
    }
    if !comps.is_empty() {
        out.push_str(if weighted { "\nMost-used components:\n\n```\n" } else { "\nCore components:\n\n```\n" });
        for ((_, _, name), t) in comps.into_iter().take(12) {
            let raw = t.raw().unwrap_or(0.0);
            let _ = writeln!(
                out,
                "{:<14} {} {:>5.1}%  {:>5} / {}",
                name.trim_end_matches(".dll"),
                bar(raw),
                raw,
                t.count(Status::Green),
                t.total
            );
        }
        out.push_str("```\n");
    }

    if !c.sources.is_empty() {
        out.push_str("\nSeeded from (names only):\n\n");
        for (id, s) in &c.sources {
            let _ = writeln!(out, "- `{id}`: {} @ `{}`", s.description, s.revision);
        }
    }
    out.push('\n');
    out.push_str(END);
    out
}

/// Replace the generated section in `readme`.
pub fn splice(readme: &str, section: &str) -> Result<String, String> {
    let start = readme.find(BEGIN).ok_or("README has no coverage:begin marker")?;
    let end = readme.find(END).ok_or("README has no coverage:end marker")? + END.len();
    if end < start {
        return Err("coverage markers out of order".into());
    }
    Ok(format!("{}{}{}", &readme[..start], section, &readme[end..]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bars() {
        assert_eq!(bar(0.0), "░".repeat(16));
        assert_eq!(bar(100.0), "█".repeat(16));
        assert_eq!(bar(50.0).chars().filter(|&c| c == '█').count(), 8);
    }

    #[test]
    fn splice_replaces_only_section() {
        let r = format!("top\n{BEGIN}\nold\n{END}\nbottom\n");
        assert_eq!(splice(&r, "NEW").unwrap(), "top\nNEW\nbottom\n");
    }
}
