//! Generates the progress section of the README and the SVG graphics it shows,
//! from `docs/ROADMAP.md` and the coverage map in `coverage/`, and the
//! README's phase table from `docs/ROADMAP.md`.

use crate::model::{Coverage, Entry, Layer, Os, Status};
use crate::roadmap::Roadmap;
use crate::svg::{self, DARK, LIGHT, percent, thousands};
use std::collections::BTreeMap;
use std::fmt::Write as _;

pub const BEGIN: &str = "<!-- coverage:begin -->";
pub const END: &str = "<!-- coverage:end -->";
pub const PHASES_BEGIN: &str = "<!-- roadmap:begin -->";
pub const PHASES_END: &str = "<!-- roadmap:end -->";

/// Where the generated graphics live, relative to the repo root.
pub const ASSET_DIR: &str = "docs/progress";

#[derive(Default)]
struct Tally {
    total: u64,
    by_status: BTreeMap<Status, u64>,
    weight: f64,
    weight_green: f64,
}

impl Tally {
    /// App-provided entries are counted but carry no weight: they are not
    /// ours to build (ADR 0055).
    fn add(&mut self, e: &Entry) {
        self.total += 1;
        *self.by_status.entry(e.status).or_default() += 1;
        if e.status == Status::AppProvided {
            return;
        }
        self.weight += e.weight;
        if e.status == Status::Green {
            self.weight_green += e.weight;
        }
    }

    fn count(&self, s: Status) -> u64 {
        self.by_status.get(&s).copied().unwrap_or(0)
    }

    /// Entries that are ours to build: the percentages' denominator.
    fn ours(&self) -> u64 {
        self.total - self.count(Status::AppProvided)
    }

    fn raw(&self) -> f64 {
        percent(self.count(Status::Green), self.ours())
    }

    fn weighted(&self) -> Option<f64> {
        (self.weight > 0.0).then(|| self.weight_green / self.weight * 100.0)
    }
}

fn layer_title(os: Os, layer: Layer) -> &'static str {
    match (os, layer) {
        (Os::Linux, Layer::Syscall) => "syscalls",
        (Os::Windows, Layer::Syscall) => "NT + win32k system services",
        (Os::Macos, Layer::Syscall) => "BSD syscalls + Mach traps",
        (Os::Linux, Layer::Api) => "user-mode API",
        (Os::Windows, Layer::Api) => "user-mode DLL exports",
        (Os::Macos, Layer::Api) => "framework API",
    }
}

fn tallies(c: &Coverage) -> (BTreeMap<Os, Tally>, BTreeMap<(Os, Layer), Tally>) {
    let mut per_os: BTreeMap<Os, Tally> = BTreeMap::new();
    let mut per_layer: BTreeMap<(Os, Layer), Tally> = BTreeMap::new();
    for e in &c.entries {
        per_os.entry(e.os).or_default().add(e);
        per_layer.entry((e.os, e.layer)).or_default().add(e);
    }
    (per_os, per_layer)
}

/// Every generated graphic: (path relative to the repo root, contents).
pub fn assets(c: &Coverage, r: &Roadmap) -> Vec<(String, String)> {
    let (per_os, _) = tallies(c);
    let mut out = Vec::new();
    let (done, total) = (r.done() as u64, r.total() as u64);
    out.push((
        format!("{ASSET_DIR}/badge-roadmap.svg"),
        svg::badge("roadmap", &format!("{done} / {total}"), percent(done, total)),
    ));
    for os in Os::ALL {
        let pct = per_os.get(&os).map_or(0.0, Tally::raw);
        out.push((format!("{ASSET_DIR}/badge-{}.svg", os.name()), svg::badge(os.title(), &format!("{pct:.1}%"), pct)));
    }
    for theme in [LIGHT, DARK] {
        out.push((format!("{ASSET_DIR}/roadmap-{}.svg", theme.name), svg::roadmap_chart(r, &theme)));
        out.push((format!("{ASSET_DIR}/coverage-{}.svg", theme.name), svg::coverage_map(c, &theme)));
    }
    out
}

fn picture(name: &str, alt: &str) -> String {
    format!(
        "<picture>\n  <source media=\"(prefers-color-scheme: dark)\" srcset=\"{ASSET_DIR}/{name}-dark.svg\">\n  \
         <img alt=\"{alt}\" src=\"{ASSET_DIR}/{name}-light.svg\" width=\"100%\">\n</picture>"
    )
}

pub fn render(c: &Coverage, r: &Roadmap) -> String {
    let (per_os, per_layer) = tallies(c);
    let mut out = String::new();
    out.push_str(BEGIN);
    out.push_str(
        "\n<!-- Generated by `cargo xtask coverage readme` from docs/ROADMAP.md and coverage/. \
         Do not edit. -->\n\n",
    );

    // Badges.
    let (done, total) = (r.done(), r.total());
    out.push_str("<p>\n");
    let _ = writeln!(
        out,
        "  <a href=\"docs/ROADMAP.md\"><img alt=\"roadmap: {done} of {total} milestones\" src=\"{ASSET_DIR}/badge-roadmap.svg\"></a>"
    );
    for os in Os::ALL {
        let pct = per_os.get(&os).map_or(0.0, Tally::raw);
        let _ = writeln!(
            out,
            "  <img alt=\"{} API coverage: {pct:.1}%\" src=\"{ASSET_DIR}/badge-{}.svg\">",
            os.title(),
            os.name()
        );
    }
    out.push_str("</p>\n\n");

    // Where we are.
    if let Some(phase) = r.current() {
        let next = phase.items.iter().find(|i| !i.done).map_or("", |i| i.text.as_str());
        let _ = writeln!(out, "**Now:** Phase {}, {}. **Next milestone:** {next}\n", phase.number, phase.title);
    }

    let _ = writeln!(out, "<a href=\"docs/ROADMAP.md\">\n{}\n</a>\n", picture("roadmap", "Roadmap progress by phase"));
    let _ = writeln!(out, "{}\n", picture("coverage", "API coverage map per OS"));
    out.push_str(
        "<sub>Block size = amount of work, green = done. The map counts callable functions: kernel calls for all \
         three OSes, plus the system libraries we rewrite for Windows and macOS (Linux's run unchanged). Interfaces \
         behind single calls, such as <code>ioctl</code> codes, <code>/proc</code> files or <code>sysctl</code> \
         names, are tracked as roadmap milestones and added here when app traces show they are used. Libraries \
         that apps bring with them (Microsoft's redistributable C++ and DirectX runtimes, \
         <a href=\"docs/adr/0055-microsoft-redistributables-run-apps-own-copies.md\">ADR 0055</a>) are \
         <em>app-provided</em>: left out of the map and of the percentages.</sub>\n\n",
    );

    // Numbers, folded away.
    out.push_str("<details>\n<summary>Coverage numbers</summary>\n\n");
    out.push_str("| OS | API coverage | App-weighted | Traces passing |\n|---|---:|---:|---:|\n");
    for os in Os::ALL {
        let t = per_os.get(&os);
        let traces = c.traces.get(&os).copied().unwrap_or_default();
        let _ = writeln!(
            out,
            "| {} | {:.1}% | {} | {} / {} |",
            os.title(),
            t.map_or(0.0, Tally::raw),
            t.and_then(Tally::weighted).map_or_else(|| "n/a".to_string(), |p| format!("{p:.1}%")),
            traces.passing,
            traces.total
        );
    }
    out.push_str("\n| OS | Layer | Entries | Green | Stub | Claimed | Missing | Blocked | App-provided |\n");
    out.push_str("|---|---|---:|---:|---:|---:|---:|---:|---:|\n");
    for os in Os::ALL {
        for layer in [Layer::Syscall, Layer::Api] {
            let title = layer_title(os, layer);
            match per_layer.get(&(os, layer)) {
                Some(t) => {
                    let _ = writeln!(
                        out,
                        "| {} | {title} | {} | {} | {} | {} | {} | {} | {} |",
                        os.title(),
                        thousands(t.total),
                        thousands(t.count(Status::Green)),
                        thousands(t.count(Status::Stub)),
                        thousands(t.count(Status::Claimed)),
                        thousands(t.count(Status::Missing)),
                        thousands(t.count(Status::BlockedByDesign)),
                        thousands(t.count(Status::AppProvided))
                    );
                }
                None => {
                    let note = if (os, layer) == (Os::Linux, Layer::Api) {
                        "runs unchanged (glibc, Mesa, GTK, Qt)"
                    } else {
                        "not mapped yet"
                    };
                    let _ = writeln!(out, "| {} | {title} | {note} | | | | | | |", os.title());
                }
            }
        }
    }
    out.push_str(
        "\n*API coverage* is green entries out of the entries that are ours to build: *app-provided* entries \
         (libraries the application or its installer supplies, ADR 0055) are listed under *Entries* but left \
         out of the percentages. *App-weighted* counts each API by how often the target apps call it; it is \
         the number that tracks real progress and appears once the call tracer exists.\n",
    );
    if !c.sources.is_empty() {
        out.push_str("\nSeeded from (names only):\n\n");
        for (id, s) in &c.sources {
            let _ = writeln!(out, "- `{id}`: {} @ `{}`", s.description, s.revision);
        }
    }
    out.push_str("\n</details>\n\n");
    out.push_str(END);
    out
}

/// The README's phase table: one row per phase of `docs/ROADMAP.md`, its
/// milestones done, and a tick once every one is.
pub fn render_phases(roadmap: &Roadmap) -> String {
    let mut out = String::from(PHASES_BEGIN);
    out.push_str("\n<!-- Generated by `cargo xtask coverage readme` from docs/ROADMAP.md. Do not edit. -->\n\n");
    out.push_str("| Phase | What it delivers | Milestones |\n|---|---|---|\n");
    for p in &roadmap.phases {
        let tick = if p.is_complete() { " \u{2705}" } else { "" };
        let title = p.title.replace('|', "\\|");
        let _ = writeln!(out, "| {} | {title} | {} of {}{tick} |", p.number, p.done(), p.items.len());
    }
    out.push('\n');
    out.push_str(PHASES_END);
    out
}

/// Replace the generated progress section in `readme`.
pub fn splice(readme: &str, section: &str) -> Result<String, String> {
    splice_between(readme, BEGIN, END, section)
}

/// Replace the generated phase table in `readme`.
pub fn splice_phases(readme: &str, table: &str) -> Result<String, String> {
    splice_between(readme, PHASES_BEGIN, PHASES_END, table)
}

/// Replace everything from `begin` to `end` (both included) with `section`.
fn splice_between(readme: &str, begin: &str, end: &str, section: &str) -> Result<String, String> {
    let start = readme.find(begin).ok_or_else(|| format!("README has no {begin} marker"))?;
    let stop = readme.find(end).ok_or_else(|| format!("README has no {end} marker"))? + end.len();
    if stop < start {
        return Err(format!("README markers {begin} and {end} out of order"));
    }
    Ok(format!("{}{}{}", &readme[..start], section, &readme[stop..]))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn splice_replaces_only_section() {
        let r = format!("top\n{BEGIN}\nold\n{END}\nmid\n{PHASES_BEGIN}\nold\n{PHASES_END}\nbottom\n");
        let r = splice(&r, "NEW").unwrap();
        assert_eq!(r, format!("top\nNEW\nmid\n{PHASES_BEGIN}\nold\n{PHASES_END}\nbottom\n"));
        assert_eq!(splice_phases(&r, "TABLE").unwrap(), "top\nNEW\nmid\nTABLE\nbottom\n");
        assert!(splice_phases("no markers", "TABLE").is_err());
    }

    #[test]
    fn phase_table_counts_and_ticks_complete_phases() {
        let roadmap = Roadmap::parse(
            "## Phase 0: Foundation\n- [x] a\n- [x] b\n## Phase 1: Kernel core\n- [x] c\n- [ ] d\n## Phase 2: Later\n",
        )
        .unwrap();
        let t = render_phases(&roadmap);
        assert!(t.starts_with(PHASES_BEGIN) && t.ends_with(PHASES_END));
        assert!(t.contains("| 0 | Foundation | 2 of 2 \u{2705} |\n"));
        assert!(t.contains("| 1 | Kernel core | 1 of 2 |\n"));
        assert!(t.contains("| 2 | Later | 0 of 0 |\n"));
    }

    #[test]
    fn app_provided_is_left_out_of_percentages() {
        use crate::model::Source;
        let mut c = Coverage::default();
        c.sources.insert("t".into(), Source { description: "test".into(), revision: "1".into() });
        let mut entries = vec![
            Entry::new(Os::Windows, Layer::Api, "kernel32.dll", "A", "t"),
            Entry::new(Os::Windows, Layer::Api, "kernel32.dll", "B", "t"),
        ];
        for s in ["x", "y", "z"] {
            let mut e = Entry::new(Os::Windows, Layer::Api, "msvcp140.dll", s, "t");
            e.status = Status::AppProvided;
            e.weight = 5.0;
            entries.push(e);
        }
        entries[0].status = Status::Green;
        entries[0].tests_visible = 1;
        entries[0].weight = 1.0;
        entries[1].weight = 3.0;
        c.merge(entries);
        assert!(c.check().is_empty());

        let (per_os, _) = tallies(&c);
        let t = &per_os[&Os::Windows];
        assert_eq!((t.total, t.ours(), t.count(Status::AppProvided)), (5, 2, 3));
        assert_eq!(t.raw(), 50.0);
        assert_eq!(t.weighted(), Some(25.0));

        let r = Roadmap::parse("## Phase 0: A\n- [ ] one\n").unwrap();
        let section = render(&c, &r);
        assert!(section.contains("| Windows | 50.0% | 25.0% |"), "{section}");
        assert!(section.contains("| Windows | user-mode DLL exports | 5 | 1 | 0 | 0 | 1 | 0 | 3 |"), "{section}");
        assert!(section.contains("Windows API coverage: 50.0%"));
    }

    #[test]
    fn assets_reference_existing_names() {
        let c = Coverage::default();
        let r = Roadmap::parse("## Phase 0: A\n- [x] one\n- [ ] two\n").unwrap();
        let section = render(&c, &r);
        for (path, svg) in assets(&c, &r) {
            assert!(svg.starts_with("<svg"), "{path}");
            let name = path.trim_start_matches(&format!("{ASSET_DIR}/"));
            let referenced =
                section.contains(name) || section.contains(&name.replace("-light.svg", "").replace("-dark.svg", ""));
            assert!(referenced, "{path} not referenced");
        }
        assert!(section.contains("**Now:** Phase 0, A. **Next milestone:** two"));
    }
}
