//! `memcpy`, `memmove`, `memset`, `bzero`, `memcmp`, `bcmp` and `strlen` in
//! assembly, in every library: Rust's generated code calls them, and a
//! Rust body could be turned back into a call to itself. libsystem_c
//! exports them (and libsystem_platform its `_platform_*` names); in the
//! other libraries they stay private.

#[cfg(target_arch = "x86_64")]
core::arch::global_asm!(
    ".globl _memcpy",
    ".globl _memmove",
    ".globl __platform_memmove",
    ".p2align 4",
    "_memcpy:",
    "_memmove:",
    "__platform_memmove:",
    "    mov rax, rdi",
    "    mov rcx, rdx",
    // Copy backwards when the destination starts inside the source.
    "    mov r8, rdi",
    "    sub r8, rsi",
    "    cmp r8, rdx",
    "    jb 3f",
    "    rep movsb",
    "    ret",
    "3:",
    "    lea rsi, [rsi + rdx - 1]",
    "    lea rdi, [rdi + rdx - 1]",
    "    std",
    "    rep movsb",
    "    cld",
    "    ret",
    "",
    ".globl _memset",
    ".globl __platform_memset",
    ".p2align 4",
    "_memset:",
    "__platform_memset:",
    "    mov r8, rdi",
    "    mov eax, esi",
    "    mov rcx, rdx",
    "    rep stosb",
    "    mov rax, r8",
    "    ret",
    "",
    ".globl _bzero",
    ".globl ___bzero",
    ".globl __platform_bzero",
    ".p2align 4",
    "_bzero:",
    "___bzero:",
    "__platform_bzero:",
    "    xor eax, eax",
    "    mov rcx, rsi",
    "    rep stosb",
    "    ret",
    "",
    ".globl _memcmp",
    ".globl _bcmp",
    ".globl __platform_memcmp",
    ".p2align 4",
    "_memcmp:",
    "_bcmp:",
    "__platform_memcmp:",
    "    xor eax, eax",
    "4:",
    "    test rdx, rdx",
    "    je 5f",
    "    movzx eax, byte ptr [rdi]",
    "    movzx ecx, byte ptr [rsi]",
    "    sub eax, ecx",
    "    jne 5f",
    "    inc rdi",
    "    inc rsi",
    "    dec rdx",
    "    jmp 4b",
    "5:",
    "    ret",
    "",
    ".globl _strlen",
    ".globl __platform_strlen",
    ".p2align 4",
    "_strlen:",
    "__platform_strlen:",
    "    mov rax, rdi",
    "6:",
    "    cmp byte ptr [rax], 0",
    "    je 7f",
    "    inc rax",
    "    jmp 6b",
    "7:",
    "    sub rax, rdi",
    "    ret",
);

// arm64 (ADR 0257): eight bytes at a time while both are aligned enough,
// then bytes.
#[cfg(target_arch = "aarch64")]
core::arch::global_asm!(
    ".globl _memcpy",
    ".globl _memmove",
    ".globl __platform_memmove",
    ".p2align 2",
    "_memcpy:",
    "_memmove:",
    "__platform_memmove:",
    "    mov x3, x0",
    // Copy backwards when the destination starts inside the source.
    "    sub x4, x0, x1",
    "    cmp x4, x2",
    "    b.lo 3f",
    "1:",
    "    cmp x2, #8",
    "    b.lo 2f",
    "    ldr x4, [x1], #8",
    "    str x4, [x3], #8",
    "    sub x2, x2, #8",
    "    b 1b",
    "2:",
    "    cbz x2, 9f",
    "    ldrb w4, [x1], #1",
    "    strb w4, [x3], #1",
    "    sub x2, x2, #1",
    "    b 2b",
    "3:",
    "    add x1, x1, x2",
    "    add x3, x3, x2",
    "4:",
    "    cbz x2, 9f",
    "    ldrb w4, [x1, #-1]!",
    "    strb w4, [x3, #-1]!",
    "    sub x2, x2, #1",
    "    b 4b",
    "9:",
    "    ret",
    "",
    ".globl _memset",
    ".globl __platform_memset",
    ".p2align 2",
    "_memset:",
    "__platform_memset:",
    "    mov x3, x0",
    "    and w1, w1, #0xff",
    "    orr w1, w1, w1, lsl #8",
    "    orr w1, w1, w1, lsl #16",
    "    orr x1, x1, x1, lsl #32",
    "1:",
    "    cmp x2, #8",
    "    b.lo 2f",
    "    str x1, [x3], #8",
    "    sub x2, x2, #8",
    "    b 1b",
    "2:",
    "    cbz x2, 3f",
    "    strb w1, [x3], #1",
    "    sub x2, x2, #1",
    "    b 2b",
    "3:",
    "    ret",
    "",
    ".globl _bzero",
    ".globl ___bzero",
    ".globl __platform_bzero",
    ".p2align 2",
    "_bzero:",
    "___bzero:",
    "__platform_bzero:",
    "    mov x2, x1",
    "    mov w1, #0",
    "    b _memset",
    "",
    ".globl _memcmp",
    ".globl _bcmp",
    ".globl __platform_memcmp",
    ".p2align 2",
    "_memcmp:",
    "_bcmp:",
    "__platform_memcmp:",
    "    mov w3, #0",
    "1:",
    "    cbz x2, 2f",
    "    ldrb w3, [x0], #1",
    "    ldrb w4, [x1], #1",
    "    subs w3, w3, w4",
    "    b.ne 2f",
    "    sub x2, x2, #1",
    "    b 1b",
    "2:",
    "    mov w0, w3",
    "    ret",
    "",
    ".globl _strlen",
    ".globl __platform_strlen",
    ".p2align 2",
    "_strlen:",
    "__platform_strlen:",
    "    mov x1, x0",
    "1:",
    "    ldrb w2, [x1], #1",
    "    cbnz w2, 1b",
    "    sub x0, x1, x0",
    "    sub x0, x0, #1",
    "    ret",
);
