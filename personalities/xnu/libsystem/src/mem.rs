//! `memcpy`, `memmove`, `memset`, `bzero`, `memcmp`, `bcmp` and `strlen` in
//! assembly, in every library: Rust's generated code calls them, and a
//! Rust body could be turned back into a call to itself. libsystem_c
//! exports them (and libsystem_platform its `_platform_*` names); in the
//! other libraries they stay private.

core::arch::global_asm!(
    ".globl _memcpy",
    ".globl _memmove",
    ".globl __platform_memmove",
    ".p2align 4",
    "_memcpy:",
    "_memmove:",
    "__platform_memmove:",
    "    mov rax, rdi",
    "    mov rcx, rdx",
    // Copy backwards when the destination starts inside the source.
    "    mov r8, rdi",
    "    sub r8, rsi",
    "    cmp r8, rdx",
    "    jb 3f",
    "    rep movsb",
    "    ret",
    "3:",
    "    lea rsi, [rsi + rdx - 1]",
    "    lea rdi, [rdi + rdx - 1]",
    "    std",
    "    rep movsb",
    "    cld",
    "    ret",
    "",
    ".globl _memset",
    ".globl __platform_memset",
    ".p2align 4",
    "_memset:",
    "__platform_memset:",
    "    mov r8, rdi",
    "    mov eax, esi",
    "    mov rcx, rdx",
    "    rep stosb",
    "    mov rax, r8",
    "    ret",
    "",
    ".globl _bzero",
    ".globl ___bzero",
    ".globl __platform_bzero",
    ".p2align 4",
    "_bzero:",
    "___bzero:",
    "__platform_bzero:",
    "    xor eax, eax",
    "    mov rcx, rsi",
    "    rep stosb",
    "    ret",
    "",
    ".globl _memcmp",
    ".globl _bcmp",
    ".globl __platform_memcmp",
    ".p2align 4",
    "_memcmp:",
    "_bcmp:",
    "__platform_memcmp:",
    "    xor eax, eax",
    "4:",
    "    test rdx, rdx",
    "    je 5f",
    "    movzx eax, byte ptr [rdi]",
    "    movzx ecx, byte ptr [rsi]",
    "    sub eax, ecx",
    "    jne 5f",
    "    inc rdi",
    "    inc rsi",
    "    dec rdx",
    "    jmp 4b",
    "5:",
    "    ret",
    "",
    ".globl _strlen",
    ".globl __platform_strlen",
    ".p2align 4",
    "_strlen:",
    "__platform_strlen:",
    "    mov rax, rdi",
    "6:",
    "    cmp byte ptr [rax], 0",
    "    je 7f",
    "    inc rax",
    "    jmp 6b",
    "7:",
    "    sub rax, rdi",
    "    ret",
);
