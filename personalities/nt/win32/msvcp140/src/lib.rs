//! Our `msvcp140.dll` (ADR 0199): the separately compiled part of Visual C++'s standard
//! library (2015 and later), so that programs which expect the Visual C++ redistributable to
//! be installed run without it. A copy the program brings (in its own directory) is found
//! first and wins, as on Windows; a copy a user installed in `System32` is kept (decision 5).
//!
//! - **Time and threads** ([`threads`]): `_Query_perf_counter`/`_frequency`,
//!   `_Xtime_get_ticks`, the `_Mtx_*` mutexes and `_Cnd_*` condition variables on SRW locks
//!   and condition variables, the `_Thrd_*` threads, `std::_Lockit`.
//! - **Exceptions** ([`exceptions`]): the `_X*` throw helpers and `_Throw_Cpp_error`, which
//!   throw the standard exception classes through `vcruntime140!_CxxThrowException` with
//!   this DLL's virtual tables, RTTI records and throw descriptors (`poly_msvcp::classes`,
//!   assembled here); `std::uncaught_exception(s)` from `vcruntime140`.
//! - **Everything else** is fail-only (ADR 0155): a function logs `stub: msvcp140!<name>` and
//!   returns 0, a variable is a zeroed block (`fail-only.txt`, `poly_msvcp::exports`).
//!
//! The behaviour is the spec sheets' (`specs/windows/msvcp140.dll`); the logic that does not
//! touch the process is `poly-msvcp`'s, tested on the host.

#![no_std]
#![allow(clippy::missing_safety_doc)]

extern crate alloc;

poly_win32_rt::process_heap_allocator!();

mod exceptions;
mod threads;

use core::cell::UnsafeCell;

/// Marks this file as Poly's own copy (ADR 0199): at boot Poly refreshes a `System32` copy
/// that holds these bytes and keeps any other (Microsoft's runtime a user installed). The same
/// text as the kernel's `OWN_COPY_MARKER` (`personalities/nt/src/layout/create.rs`); the
/// kernel's `build.rs` checks it is in the file.
static OWN_COPY_MARKER: &[u8] = b"Poly's own copy of a Visual C++ runtime DLL (ADR 0199)";

/// The entry point: nothing to set up (the exception records are static, the locks start
/// zeroed).
#[unsafe(no_mangle)]
pub extern "system" fn msvcp140_main(_module: *mut u8, _reason: u32, _reserved: *mut u8) -> i32 {
    core::hint::black_box(OWN_COPY_MARKER.as_ptr());
    1
}

/// A zeroed, writable block of `N` bytes: an exported variable that is not real yet.
#[derive(Debug)]
#[repr(C, align(16))]
pub struct Zeroed<const N: usize>(UnsafeCell<[u8; N]>);

// SAFETY: the bytes belong to the program that imports them; this DLL never touches them.
unsafe impl<const N: usize> Sync for Zeroed<N> {}

impl<const N: usize> Zeroed<N> {
    pub const ZERO: Self = Zeroed(UnsafeCell::new([0; N]));
}

/// The fail-only exports (generated by `build.rs` from `fail-only.txt`).
mod stubs {
    include!(concat!(env!("OUT_DIR"), "/stubs.rs"));
}
