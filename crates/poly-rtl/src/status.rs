/// `RtlNtStatusToDosError` / `RtlNtStatusToDosErrorNoTeb`.
pub fn nt_status_to_dos_error(status: NtStatus) -> u32 {
    let s = status.0;
    if (s >> 16) & 0x0FFF == FACILITY_NTWIN32 {
        return s & 0xFFFF;
    }
    match TABLE.binary_search_by_key(&s, |&(k, _)| k) {
        Ok(i) => TABLE[i].1,
        Err(_) => ERROR_MR_MID_NOT_FOUND,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_table_is_sorted_without_duplicates() {
        assert!(TABLE.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn known_codes_map() {
        assert_eq!(nt_status_to_dos_error(NtStatus(0)), ERROR_SUCCESS);
        assert_eq!(nt_status_to_dos_error(NtStatus(0xC000_0034)), ERROR_FILE_NOT_FOUND);
        assert_eq!(nt_status_to_dos_error(NtStatus(0xC000_003A)), ERROR_PATH_NOT_FOUND);
        assert_eq!(nt_status_to_dos_error(NtStatus(0xC000_0022)), ERROR_ACCESS_DENIED);
        assert_eq!(nt_status_to_dos_error(NtStatus(0xC000_0135)), ERROR_MOD_NOT_FOUND);
        assert_eq!(nt_status_to_dos_error(NtStatus(0xC000_0017)), ERROR_NOT_ENOUGH_MEMORY);
        assert_eq!(nt_status_to_dos_error(NtStatus(0x8000_0005)), ERROR_MORE_DATA);
        assert_eq!(nt_status_to_dos_error(NtStatus(0x0000_0103)), ERROR_IO_PENDING);
    }

    #[test]
    fn win32_facility_carries_the_error() {
        // A failure of facility NTWIN32 wrapping ERROR_SHARING_VIOLATION.
        assert_eq!(nt_status_to_dos_error(NtStatus(0xC007_0020)), ERROR_SHARING_VIOLATION);
        assert_eq!(nt_status_to_dos_error(NtStatus(0x8007_0005)), ERROR_ACCESS_DENIED);
    }

    #[test]
    fn unknown_codes_are_mr_mid_not_found() {
        assert_eq!(nt_status_to_dos_error(NtStatus(0xC0DE_0001)), ERROR_MR_MID_NOT_FOUND);
        assert_eq!(nt_status_to_dos_error(NtStatus(0x0000_0001)), ERROR_MR_MID_NOT_FOUND);
    }
}
