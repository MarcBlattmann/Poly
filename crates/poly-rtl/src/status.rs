//! `RtlNtStatusToDosError`: an `NTSTATUS` to the Win32 error code
//! `GetLastError` reports.
//!
//! The pairs come from Microsoft's public support article "INFO: Mapping NT
//! Status Error Codes to Win32 Error Codes" (KB113996) as Poly reads it; the
//! status values are `ntstatus.h`'s, the error values `winerror.h`'s, and
//! both names are kept beside each number. Two rules from the reference
//! page of `RtlNtStatusToDosError` (Learn, WDK): a status of facility
//! `FACILITY_NTWIN32` (7, `ntstatus.h`) carries a Win32 error in its low 16
//! bits, and a status the table does not know gives
//! `ERROR_MR_MID_NOT_FOUND`. Which other codes Windows maps, and to what, is
//! for the spec agent to confirm (ADR 0071).

