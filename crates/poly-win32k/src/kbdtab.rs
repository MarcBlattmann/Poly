//! The keyboard layouts' key tables: data only (ADR 0212).
//!
//! One row per key of the layouts' character keys (digits, letters, the
//! `VK_OEM_*` keys, Space, the control keys, the numeric pad and a few keys
//! that make no character): the virtual key, its scan code in the layout (0:
//! the layout has no such key) and the ten cells of the spec sheet
//! `ToUnicodeEx.yaml` (`table_format`): the character for no modifier, Shift,
//! Caps Lock, Shift and Caps Lock, Ctrl, Ctrl+Shift, AltGr (Ctrl+Alt),
//! AltGr+Shift, Alt and AltGr+Caps Lock. `NO` is no character, a cell with
//! [`DEAD`] set is a dead key's spacing character. The cells are the sheet's
//! tables, written out one by one (`tue_*_table`'s recorded results).

/// "No character" (U+FFFF is a noncharacter).
pub const NO: u32 = 0xFFFF;
/// Set in a cell for a dead key; the low bits are its spacing character.
pub const DEAD: u32 = 0x8000_0000;

/// A key: virtual key, scan code (0: none in this layout) and the ten cells.
pub type Row = (u8, u8, [u32; 10]);

