/* The fonts as CFData (not copied: the data is static). */
static __attribute__((unused)) CFDataRef pt_data(int bold) {
    return bold ? CFDataCreateWithBytesNoCopy(kCFAllocatorDefault, poly_font_bold, sizeof poly_font_bold, kCFAllocatorNull)
                : CFDataCreateWithBytesNoCopy(kCFAllocatorDefault, poly_font_regular, sizeof poly_font_regular, kCFAllocatorNull);
}

/* A font descriptor made from the embedded data (not registered). */
static __attribute__((unused)) CTFontDescriptorRef pt_descriptor(int bold) {
    return CTFontManagerCreateFontDescriptorFromData(pt_data(bold));
}

/* The embedded font at `size`, made from its descriptor (not registered). */
static __attribute__((unused)) CTFontRef pt_font(int bold, CGFloat size) {
    CTFontDescriptorRef d = pt_descriptor(bold);
    return d ? CTFontCreateWithFontDescriptor(d, size, NULL) : NULL;
}

/* Write both embedded fonts into the scratch directory as PolyTest-Regular.ttf and
 * PolyTest-Bold.ttf and register them for this process (CTFontManagerRegisterFontsForURL,
 * scope process); returns 1 when both registrations succeeded. */
static __attribute__((unused)) int pt_register(void) {
    if (!cf_write_file("PolyTest-Regular.ttf", (const char *)poly_font_regular, sizeof poly_font_regular)) return 0;
    if (!cf_write_file("PolyTest-Bold.ttf", (const char *)poly_font_bold, sizeof poly_font_bold)) return 0;
    int ok = 1;
    for (int i = 0; i < 2; i++) {
        CFURLRef u = CFURLCreateWithFileSystemPath(kCFAllocatorDefault, i ? CFSTR("PolyTest-Bold.ttf") : CFSTR("PolyTest-Regular.ttf"), kCFURLPOSIXPathStyle, false);
        CFURLRef abs = CFURLCopyAbsoluteURL(u);
        ok &= CTFontManagerRegisterFontsForURL(abs, kCTFontManagerScopeProcess, NULL) ? 1 : 0;
    }
    return ok;
}

/* A font from a file in the scratch directory (DejaVu, see above), or NULL. */
static __attribute__((unused)) CTFontRef pt_file_font(const char *name, CGFloat size) {
    CFStringRef p = CFStringCreateWithCString(kCFAllocatorDefault, name, kCFStringEncodingUTF8);
    CFURLRef u = CFURLCreateWithFileSystemPath(kCFAllocatorDefault, p, kCFURLPOSIXPathStyle, false);
    CFArrayRef ds = CTFontManagerCreateFontDescriptorsFromURL(CFURLCopyAbsoluteURL(u));
    if (!ds || CFArrayGetCount(ds) < 1) return NULL;
    return CTFontCreateWithFontDescriptor((CTFontDescriptorRef)CFArrayGetValueAtIndex(ds, 0), size, NULL);
}

/* The whole file `name` (up to 2 MB) as CFData, or NULL. */
static __attribute__((unused)) CFDataRef pt_read_file(const char *name) {
    static unsigned char buf[1 << 21];
    sysret fd = bsd3(SYS_open, name, 0, 0);
    if (fd.err) return NULL;
    size_t n = 0;
    for (;;) {
        sysret r = bsd3(SYS_read, fd.ret, buf + n, sizeof buf - n);
        if (r.err || r.ret <= 0) break;
        n += (size_t)r.ret;
    }
    bsd3(SYS_close, fd.ret, 0, 0);
    return n ? CFDataCreate(kCFAllocatorDefault, buf, (CFIndex)n) : NULL;
}

/* Register DejaVu files that the test got in its scratch directory (see `poly-mac: fonts`)
 * for this process; returns how many registrations succeeded. */
static __attribute__((unused)) int pt_register_files(const char *const *names, int n) {
    int ok = 0;
    for (int i = 0; i < n; i++) {
        CFStringRef p = CFStringCreateWithCString(kCFAllocatorDefault, names[i], kCFStringEncodingUTF8);
        CFURLRef u = CFURLCreateWithFileSystemPath(kCFAllocatorDefault, p, kCFURLPOSIXPathStyle, false);
        ok += CTFontManagerRegisterFontsForURL(CFURLCopyAbsoluteURL(u), kCTFontManagerScopeProcess, NULL) ? 1 : 0;
    }
    return ok;
}

/* The PostScript name of a font (empty for NULL), into `buf`. */
static __attribute__((unused)) const char *pt_ps(CTFontRef f, char *buf, CFIndex n) {
    buf[0] = 0;
    if (f) cf_c(CTFontCopyPostScriptName(f), buf, n);
    return buf;
}
/* Whether the PostScript name of `f` is exactly `want`. */
static __attribute__((unused)) int pt_is(CTFontRef f, const char *want) {
    char b[256];
    return f && str_eq(pt_ps(f, b, sizeof b), want);
}

/* `CKF(value, want)` checks a number against what is expected to within 0.01 and shows
 * the value times 100 when it fails. */
#define CKF(v, want) check(#v " is " #want, near((double)(v), (double)(want)), (i64)((v) * 100))

/* An attributed string of the UTF-8 text with one font over all of it. */
static __attribute__((unused)) CFAttributedStringRef pt_attributed(const char *utf8, CTFontRef font) {
    CFStringRef s = CFStringCreateWithCString(kCFAllocatorDefault, utf8, kCFStringEncodingUTF8);
    CFMutableAttributedStringRef as = CFAttributedStringCreateMutable(kCFAllocatorDefault, 0);
    CFAttributedStringReplaceString(as, CFRangeMake(0, 0), s);
    if (font) CFAttributedStringSetAttribute(as, CFRangeMake(0, CFStringGetLength(s)), kCTFontAttributeName, font);
    return as;
}

/* The line of the UTF-8 text in the font. */
static __attribute__((unused)) CTLineRef pt_line(const char *utf8, CTFontRef font) {
    return CTLineCreateWithAttributedString(pt_attributed(utf8, font));
}

/* Round to 1/100 and print as a decimal with two places (never -0.00), so results do not
 * depend on float noise. */
static __attribute__((unused)) void value_f(const char *name, double v) {
    long long m = (long long)(v * 100.0 + (v < 0 ? -0.5 : 0.5));
    char buf[40];
    int n = 0, neg = m < 0;
    unsigned long long u = neg ? (unsigned long long)(-m) : (unsigned long long)m;
    char t[24];
    int k = 0;
    do t[k++] = (char)('0' + u % 10), u /= 10;
    while (u);
    while (k < 3) t[k++] = '0';
    if (neg && m != 0) buf[n++] = '-';
    for (int i = k - 1; i >= 2; i--) buf[n++] = t[i];
    buf[n++] = '.';
    for (int i = 1; i >= 0; i--) buf[n++] = t[i];
    buf[n] = 0;
    value_str(name, buf);
}

/* Whether `v` is within 0.01 of `want`. */
static __attribute__((unused)) int near(double v, double want) { return v > want - 0.01 && v < want + 0.01; }

/* An 8-bit gray bitmap context w x h, cleared to `clear` (0 black .. 255 white), whose
 * pixels are at `*data` (row 0 is the top row). */
static __attribute__((unused)) CGContextRef pt_bitmap(int w, int h, unsigned char clear, unsigned char **data) {
    static unsigned char pixels[4096 * 4];
    CGColorSpaceRef cs = CGColorSpaceCreateWithName(kCGColorSpaceGenericGrayGamma2_2);
    for (int i = 0; i < w * h; i++) pixels[i] = clear;
    *data = pixels;
    return CGBitmapContextCreate(pixels, (size_t)w, (size_t)h, 8, (size_t)w, cs, (CGBitmapInfo)kCGImageAlphaNone);
}

/* Print the pixels as rows of two hex digits per pixel, row 0 (top) first. */
static __attribute__((unused)) void pt_dump(const char *name, const unsigned char *px, int w, int h) {
    static const char H[] = "0123456789abcdef";
    for (int y = 0; y < h; y++) {
        char row[200], label[64];
        int j = 0;
        for (int x = 0; x < w && j < 190; x++) row[j++] = H[px[y * w + x] >> 4], row[j++] = H[px[y * w + x] & 15];
        row[j] = 0;
        int k = 0;
        for (const char *p = name; *p && k < 50; p++) label[k++] = *p;
        label[k++] = '.';
        label[k++] = (char)('0' + y / 10);
        label[k++] = (char)('0' + y % 10);
        label[k] = 0;
        value_str(label, row);
    }
}

/* The UTF-8 text of a CFString into `buf` (empty when NULL). */
static __attribute__((unused)) const char *pt_str(CFStringRef s, char *buf, CFIndex n) { return cf_c(s, buf, n); }

