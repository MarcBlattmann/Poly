/*
 * Support for macOS test programs about CoreText (ADR 0182, the CoreText batch). A
 * test that includes this header says so in its header comment with the line
 * `poly-mac: coretext` (`mac build` then links it with -framework CoreText,
 * CoreGraphics and CoreFoundation and lets it import their own symbols; all other
 * tests import nothing, see poly_mtest.h), and defines `int test_main(void)`.
 * CoreText, CoreGraphics and CoreFoundation types and constants come from the public
 * SDK headers. A test that needs DejaVu Sans 2.37 says so with a second line
 * `poly-mac: fonts DejaVuSans.ttf DejaVuSans-Bold.ttf`: the runner then puts those
 * files (fetched by `cargo xtask fonts fetch`, never committed) in the test's scratch
 * directory, so they are opened by the relative name `DejaVuSans.ttf`.
 *
 * Results do not depend on Apple's fonts: the tests use fonts they bring. Two small
 * TrueType fonts, "PolyTest Regular" and "PolyTest Bold", are embedded below (made by
 * tests/macos/fonts/mkfont.py for this purpose from the public TrueType table
 * formats; public domain). Their design (units per em 1000):
 *
 *   glyph   code point       advance  outline (units)
 *   .notdef -                500      box 50..450 x 0..700
 *   space   U+0020           300      empty
 *   A       U+0041           600      box 100..500 x 0..700 (cap height)
 *   B       U+0042           500      box 100..400 x 0..500 (x height)
 *   V       U+0056           700      triangle (0,0) (350,700) (700,0)
 *   W       U+0057           1400     composite of two V, the second shifted by 700
 *   a       U+0061           500      box 50..450 x 0..500
 *   g       U+0067           500      box 50..450 x -200..400
 *   e-acute U+00E9           500      composite of a and the mark (shifted 150, 520)
 *   mark    U+0301           0        box 0..100 x 0..100
 *   box     U+1F600          900      box 0..800 x 0..800 (cmap format 12)
 *   O       U+004F           800      box 0..700 x 0..700 with a hole 200..500 x 200..500
 *
 * Bold has the A and B glyphs 60 units wider. Vertical metrics are chosen to differ
 * between the tables: hhea 800 / -200 / line gap 100, OS/2 typo 700 / -300 / 50, win
 * 900 / 250, capHeight 700, xHeight 500; a legacy `kern` pair A,V = -100 and V,A = -80;
 * post italic angle 0, underline position -100, thickness 50. Names: family
 * "PolyTest", style "Regular" or "Bold", full "PolyTest Regular", PostScript
 * "PolyTest-Regular" / "PolyTest-Bold".
 *
 * What is reported does not go through the code under test: output is the raw `write`
 * system call of poly_mtest.h (`check`, `value`, `finish` as in poly_mcf.h, which this
 * header includes). Never print addresses, times, pids or system font names a test is not
 * about; every test runs several times per architecture and must print the same bytes.
 * Each test starts in a fresh, empty scratch directory with an empty environment.
 *
 * Written for Poly from public sources and from observation only. No Apple or third-party
 * source was read; no code is copied from anywhere.
 */
