/// `poly.nt.trail[=N]` (`poly_personality_nt::trace::TRAIL_FLAG`): the calls each process keeps;
/// 0 is off.
static TRAIL_LEN: core::sync::atomic::AtomicUsize = core::sync::atomic::AtomicUsize::new(0);
/// `poly.nt.only=<text>` (`poly_personality_nt::trace::ONLY_FLAG`): empty for every process.
static ONLY: Mutex<String> = Mutex::new(String::new());
/// The command lines of NT processes, read from their PEB at their first system call while a
/// diagnostic that names processes is on (`poly.nt.only`, `poly.nt.waits`).
static COMMAND_LINES: Mutex<BTreeMap<u32, String>> = Mutex::new(BTreeMap::new());
/// `poly.nt.trail.skip=<name>,<name>`: services the trail leaves out (`NtReadFile`), so a busy
/// loop does not push the start-up out of it.
static TRAIL_SKIP: Mutex<String> = Mutex::new(String::new());
/// The trails of `poly.nt.trail`, by process.
/// Kept per thread, `(pid, tid)`, so a busy thread does not push a quiet one's last calls out.
static TRAILS: Mutex<BTreeMap<(u32, u32), poly_personality_nt::trace::Trail>> = Mutex::new(BTreeMap::new());

/// `poly.nt.only` was given.
static ONLY_SET: core::sync::atomic::AtomicBool = core::sync::atomic::AtomicBool::new(false);

/// Whether a diagnostic needs the processes' command lines.
fn wants_command_lines() -> bool {
    WAITS_EVERY.load(core::sync::atomic::Ordering::Relaxed) != 0
        || MEM_EVERY.load(core::sync::atomic::Ordering::Relaxed) != 0
        || ONLY_SET.load(core::sync::atomic::Ordering::Relaxed)
}

/// The calling process's command line (`PEB.ProcessParameters`,
/// `RTL_USER_PROCESS_PARAMETERS.CommandLine`: `winternl.h`; at the offsets of a 64-bit or a
/// 32-bit process, ADR 0186), at most 512 characters.
fn read_command_line(pid: u32) -> Option<String> {
    let (peb, l) = with(|s| s.processes.get(&ProcessId(pid)).map(|p| (p.peb, p.layout())))?;
    let n = l.ptr as usize;
    let mut b = [0u8; 8];
    user::copy_from_user(&mut b[..n], peb.checked_add(l.peb_process_parameters)?).ok()?;
    let params = u64::from_le_bytes(b);
    let mut us = [0u8; 16];
    user::copy_from_user(&mut us[..2 * n], params.checked_add(l.pp_command_line)?).ok()?;
    let len = (u16::from_le_bytes([us[0], us[1]]) as usize / 2).min(512);
    let mut buf = [0u8; 8];
    buf[..n].copy_from_slice(&us[n..2 * n]);
    let buffer = u64::from_le_bytes(buf);
    let mut bytes = alloc::vec![0u8; len * 2];
    user::copy_from_user(&mut bytes, buffer).ok()?;
    let units: Vec<u16> = bytes.chunks_exact(2).map(|c| u16::from_le_bytes([c[0], c[1]])).collect();
    Some(String::from_utf16_lossy(&units))
}

/// Remember the calling process's command line if a diagnostic needs it and it is not known.
fn note_command_line(pid: u32) {
    if !wants_command_lines() || COMMAND_LINES.lock().contains_key(&pid) {
        return;
    }
    if let Some(line) = read_command_line(pid) {
        COMMAND_LINES.lock().insert(pid, line);
    }
}

/// Whether `poly.nt.only` selects process `pid` (for the trace and the trail).
fn selected(pid: u32) -> bool {
    let only = ONLY.lock().clone();
    let lines = COMMAND_LINES.lock();
    poly_personality_nt::trace::selects(lines.get(&pid).map(String::as_str), &only)
}

/// `poly.nt.trail`: write thread `tid` of process `pid`'s last calls (an exception with `code`
/// was handed to it).
fn write_trail(pid: u32, tid: u32, code: u32) {
    let calls = TRAILS.lock().get_mut(&(pid, tid)).map(|t| t.take()).unwrap_or_default();
    let line = COMMAND_LINES.lock().get(&pid).cloned().unwrap_or_default();
    crate::kprintln!("nt-trail: p{pid} t{tid} exception {code:#x}, its last {} calls: {line}", calls.len());
    for c in calls {
        crate::kprintln!("nt-trail: {c}");
    }
    // The process's other threads, their calls of the last few seconds: who woke the thread and
    // what ran beside it.
    let since = (crate::time::now_ns() / 1000).saturating_sub(TRAIL_OTHERS_US);
    let others: Vec<(u32, Vec<String>)> = TRAILS
        .lock()
        .iter()
        .filter(|((p, t), _)| *p == pid && *t != tid)
        .map(|((_, t), trail)| (*t, trail.lines().filter(|l| trail_time_us(l) >= since).cloned().collect()))
        .collect();
    for (t, lines) in others.into_iter().filter(|(_, l)| !l.is_empty()) {
        crate::kprintln!("nt-trail: p{pid} t{t} beside it, its calls of the last {} ms:", TRAIL_OTHERS_US / 1000);
        for l in lines {
            crate::kprintln!("nt-trail:   {l}");
        }
    }
}

/// How far back [`write_trail`] shows the other threads' calls.
const TRAIL_OTHERS_US: u64 = 3_000_000;

/// The time a trail line was taken at (its ` @<µs>us`), 0 if it has none.
fn trail_time_us(line: &str) -> u64 {
    line.rsplit_once(" @").and_then(|(_, rest)| rest.split_once("us")).and_then(|(n, _)| n.parse().ok()).unwrap_or(0)
}

/// Start the wait reporter (and the memory reporter) once, with the first NT program.
fn start_waits_reporter() {
    use core::sync::atomic::Ordering::SeqCst;
    if MEM_EVERY.load(SeqCst) != 0
        && !MEM_STARTED.swap(true, SeqCst)
        && let Ok(tid) = thread::spawn_named("nt-mem", mem_main, 0)
    {
        let _ = thread::detach(tid);
    }
    if WAITS_EVERY.load(SeqCst) == 0 || WAITS_STARTED.swap(true, SeqCst) {
        return;
    }
    if let Ok(tid) = thread::spawn_named("nt-waits", waits_main, 0) {
        let _ = thread::detach(tid);
    }
}

/// One `poly.nt.mem` report: the frame allocator's frames by user, then every NT process's pages.
pub fn log_memory() {
    let (free, total) = crate::frames::FRAMES.lock().as_ref().map_or((0, 0), |f| (f.free_frames(), f.total_frames()));
    let user = user::user_frames();
    let cache = crate::fs::cache::frames();
    let heap = crate::heap::stats().pages_held as u64;
    let rest = total.saturating_sub(free + user + cache + heap);
    crate::kprintln!(
        "nt-mem: at {} ms frames total {total} free {free} user {user} cache {cache} heap {heap} rest {rest} MiB: free {} user {} cache {} heap {} rest {}",
        crate::time::now_ns() / 1_000_000,
        free / 256,
        user / 256,
        cache / 256,
        heap / 256,
        rest / 256
    );
    let mut sum = [0u64; 3];
    for (pid, memory) in io::memories() {
        let (resident, cached, shared) = memory.page_counts();
        let own = resident.saturating_sub(cached + shared);
        sum[0] += own;
        sum[1] += cached;
        sum[2] += shared;
        let line = COMMAND_LINES.lock().get(&pid).cloned().unwrap_or_default();
        let kind = line.split(' ').find(|a| a.starts_with("--type=")).unwrap_or("");
        crate::kprintln!("nt-mem: p{pid} own {own} cached {cached} shared {shared} pages {kind}");
    }
    let (images, made, found) = backend::image_share_counts();
    crate::kprintln!(
        "nt-mem: all NT processes own {} cached {} shared {} pages; {images} images share pages, {made} image pages made, {found} faults found a shared one",
        sum[0],
        sum[1],
        sum[2]
    );
}

fn mem_main(_: usize) -> usize {
    let every = u64::from(MEM_EVERY.load(core::sync::atomic::Ordering::SeqCst).max(1));
    loop {
        thread::sleep(core::time::Duration::from_secs(every));
        log_memory();
    }
}

fn waits_main(_: usize) -> usize {
    let every = u64::from(WAITS_EVERY.load(core::sync::atomic::Ordering::SeqCst).max(1));
    loop {
        thread::sleep(core::time::Duration::from_secs(every));
        let lines: alloc::vec::Vec<alloc::string::String> = with(|s| {
            let objects = &s.sys.objects;
            objects
                .pending_wait_list()
                .iter()
                .map(|w| {
                    let pid = s.processes.values().find(|p| p.thread(w.thread).is_some()).map_or(0, |p| p.pid.0);
                    let mut line = alloc::format!(
                        "nt-waits: p{pid} t{} {}{} on",
                        w.thread.0,
                        if w.all { "all" } else { "any" },
                        if w.alertable { " alertable" } else { "" }
                    );
                    for &o in &w.objects {
                        let kind = objects.object_type(o);
                        let name = objects.object_name(o).map(|n| alloc::string::String::from_utf16_lossy(&n));
                        let held: Vec<String> =
                            objects.holders(o).iter().map(|(p, h)| alloc::format!("p{}:{:#x}", p.0, h.0)).collect();
                        line.push_str(&alloc::format!(
                            " [{:?} {} cookie {:#x} held {}]",
                            kind,
                            name.as_deref().unwrap_or("-"),
                            objects.cookie(o).unwrap_or(0),
                            held.join(",")
                        ));
                    }
                    line
                })
                .collect()
        });
        crate::kprintln!("nt-waits: {} blocked waits at {} ms", lines.len(), crate::time::now_ns() / 1_000_000);
        for l in lines {
            crate::kprintln!("{l}");
        }
        let io: Vec<String> = with(|s| {
            let io = &s.sys.io;
            let mut lines = io.np_debug_lines(&s.sys.objects);
            lines.extend(io.port_debug_lines(&s.sys.objects));
            lines.extend(s.sys.win32k.queue_debug_lines(&s.sys.objects));
            lines.push(alloc::format!(
                "requests waiting {:?}, completions queued {}",
                io.pending_by_process(),
                io.queued_completions()
            ));
            lines
        });
        for l in io {
            crate::kprintln!("nt-waits: {l}");
        }
        // The trails of the selected processes (`poly.nt.trail` with `poly.nt.only`): what each did
        // last before it went quiet. They are kept, not cleared.
        let trails: Vec<((u32, u32), Vec<String>)> =
            TRAILS.lock().iter().map(|(k, t)| (*k, t.lines().cloned().collect())).collect();
        for ((pid, tid), lines) in trails {
            crate::kprintln!("nt-waits: p{pid} t{tid} last {} calls:", lines.len());
            for l in lines {
                crate::kprintln!("nt-waits:   {l}");
            }
        }
        // Threads that are suspended (a count above 0) or parked suspended, with where they stopped.
        let suspended: Vec<String> = with(|s| {
            s.processes
                .values()
                .flat_map(|p| p.threads.iter().map(move |t| (p.pid.0, t.thread)))
                .filter_map(|(pid, t)| {
                    let c = s.ctl.get(&t)?;
                    (c.suspend_count > 0 || c.suspended_ctx.is_some()).then(|| {
                        alloc::format!(
                            "nt-waits: p{pid} t{} suspend count {} {}",
                            t.0,
                            c.suspend_count,
                            c.suspended_ctx
                                .map_or(String::from("running"), |x| alloc::format!("parked at {:#x}", x.rip))
                        )
                    })
                })
                .collect()
        });
        for l in suspended {
            crate::kprintln!("{l}");
        }
        // The CPU time of every thread of the known processes that used more than 100 ms: a thread
        // that is in no wait and makes no calls but whose time grows is busy (user: its own code;
        // system: the kernel, a fault it keeps taking).
        let pids: Vec<u32> = COMMAND_LINES.lock().keys().copied().collect();
        for pid in pids {
            let process = crate::process::find(pid);
            let memory = io::memory_of(pid);
            let teb = with(|s| s.processes.get(&ProcessId(pid)).and_then(|p| p.threads.first()).map(|t| t.teb));
            let modules = match (&memory, teb) {
                (Some(m), Some(teb)) => {
                    poly_personality_nt::diag::modules(&|at, buf: &mut [u8]| m.read(at, buf).is_ok(), teb)
                }
                _ => Vec::new(),
            };
            for (tid, t) in crate::cputime::threads_of(pid) {
                if t.total_ns() > 100_000_000 {
                    let rip = process
                        .as_ref()
                        .and_then(|p| p.thread_flags(tid))
                        .map_or(0, |f| f.last_user_rip.load(core::sync::atomic::Ordering::Relaxed));
                    let at = modules
                        .iter()
                        .find(|m| rip >= m.base && rip - m.base < m.size)
                        .map_or(alloc::format!("{rip:#x}"), |m| alloc::format!("{}+{:#x}", m.name, rip - m.base));
                    crate::kprintln!(
                        "nt-waits: p{pid} t{tid} cpu user {} ms system {} ms, last seen in user mode at {at}",
                        t.user_ns / 1_000_000,
                        t.system_ns / 1_000_000
                    );
                }
            }
        }
        let known: Vec<(u32, String)> = COMMAND_LINES.lock().iter().map(|(p, l)| (*p, l.clone())).collect();
        for (pid, line) in known {
            crate::kprintln!("nt-waits: p{pid} is {line}");
        }
    }
}

/// Read the NT personality's kernel arguments (before the first program).
pub fn configure(boot: &crate::boot_info::BootInfo) {
    let exceptions = boot.arg(poly_personality_nt::diag::EXCEPTIONS_FLAG);
    if exceptions.is_some() || boot.has_flag(poly_personality_nt::diag::EXCEPTIONS_FLAG) {
        let words = poly_personality_nt::diag::exception_stack_words(exceptions);
        EXCEPTIONS.store(words as u32, core::sync::atomic::Ordering::Relaxed);
        crate::kprintln!("nt: logging every exception delivered to user mode, {words} stack quadwords");
    }
    apitrace::configure(boot);
    let memory = boot.arg(poly_personality_nt::diag::EXCEPTION_MEMORY_FLAG);
    if memory.is_some() || boot.has_flag(poly_personality_nt::diag::EXCEPTION_MEMORY_FLAG) {
        let bytes = poly_personality_nt::diag::exception_memory_bytes(memory);
        EXCEPTION_MEMORY.store(bytes as u32, core::sync::atomic::Ordering::Relaxed);
    }
    use poly_personality_nt::trace::{ONLY_FLAG, TRAIL_FLAG, trail_len};
    if let Some(n) = trail_len(boot.has_flag(TRAIL_FLAG), boot.arg(TRAIL_FLAG)) {
        TRAIL_LEN.store(n, core::sync::atomic::Ordering::Relaxed);
        crate::kprintln!("nt: every process keeps its last {n} system calls for a breakpoint (poly.nt.trail)");
    }
    if let Some(skip) = boot.arg("poly.nt.trail.skip") {
        *TRAIL_SKIP.lock() = String::from(skip);
    }
    if let Some(only) = boot.arg(ONLY_FLAG) {
        *ONLY.lock() = String::from(only);
        ONLY_SET.store(true, core::sync::atomic::Ordering::Relaxed);
        crate::kprintln!("nt: the trace and the trail are kept for processes whose command line has {only:?}");
    }
    if let Some(v) = boot.arg("poly.nt.mem") {
        MEM_EVERY.store(v.parse().unwrap_or(5), core::sync::atomic::Ordering::Relaxed);
    } else if boot.has_flag("poly.nt.mem") {
        MEM_EVERY.store(5, core::sync::atomic::Ordering::Relaxed);
    }
    if let Some(v) = boot.arg("poly.nt.waits") {
        WAITS_EVERY.store(v.parse().unwrap_or(30), core::sync::atomic::Ordering::Relaxed);
    } else if boot.has_flag("poly.nt.waits") {
        WAITS_EVERY.store(30, core::sync::atomic::Ordering::Relaxed);
    }
    if WAITS_EVERY.load(core::sync::atomic::Ordering::Relaxed) != 0 {
        user::SAMPLE_USER_RIP.store(true, core::sync::atomic::Ordering::Relaxed);
    }
    if boot.arg(poly_personality_nt::trace::FLAG) == Some("all") {
        TRACE.store(2, core::sync::atomic::Ordering::Relaxed);
        crate::kprintln!("nt: tracing every system call (poly.nt.trace=all)");
    } else if boot.has_flag(poly_personality_nt::trace::FLAG) {
        TRACE.store(1, core::sync::atomic::Ordering::Relaxed);
        crate::kprintln!("nt: tracing system calls (poly.nt.trace)");
    }
    if let Some(v) = boot.arg(TOKEN_ARG) {
        match poly_personality_nt::security::Logon::parse(v) {
            Some(l) => {
                *LOGON.lock() = l;
                crate::kprintln!("nt: Windows programs run with the {v} token (poly.win.token)");
            }
            None => crate::kprintln!("nt: poly.win.token={v} is not standard, elevated or admin; ignored"),
        }
    }
    if let Some(v) = boot.arg(poly_personality_nt::consent::ANSWER_ARG) {
        *UAC_ANSWER.lock() = poly_personality_nt::consent::Broker::parse_hook(v);
        crate::kprintln!("nt: consent prompts are answered {v:?} at once (poly.uac.answer, a test hook)");
    }
    if boot.arg(SESSION_ARG) == Some("interactive") {
        INTERACTIVE.store(true, core::sync::atomic::Ordering::Relaxed);
        crate::kprintln!("nt: win32k reproduces the interactive desktop session (1920x1080)");
    } else if boot.arg(SESSION_ARG) == Some("interactive-bottom") {
        INTERACTIVE.store(true, core::sync::atomic::Ordering::Relaxed);
        TASKBAR_BOTTOM.store(true, core::sync::atomic::Ordering::Relaxed);
        crate::kprintln!("nt: win32k reproduces the interactive desktop session (1920x1080, taskbar at the bottom)");
    }
    let (display, scale) = (boot.arg("poly.win32k.display"), boot.arg("poly.win32k.scale"));
    if INTERACTIVE.load(core::sync::atomic::Ordering::Relaxed) && (display.is_some() || scale.is_some()) {
        match poly_win32k::dpiscale::parse_display(display, scale) {
            Some(((w, h), p)) => {
                *DISPLAY.lock() = Some(((w, h), p));
                crate::kprintln!("nt: the session's screen is {w}x{h} at {p} percent");
            }
            None => crate::kprintln!("nt: poly.win32k.display / poly.win32k.scale not understood; ignored"),
        }
    }
}

/// The full `NTSTATUS` the processes the test-run protocol watches ended
/// with ([`watch_exit_status`]; the process's own `ExitStatus` keeps only
/// its low 8 bits): `(status, final)`, final once `NtTerminateProcess`
/// set it, so the threads that end after it do not change it (ADR 0075).
static EXIT_WATCH: Mutex<BTreeMap<u32, Option<(u32, bool)>>> = Mutex::new(BTreeMap::new());

/// Remember the `NTSTATUS` NT process `pid` will end with, for
/// [`take_exit_status`] (the `poly.init` program: `POLY-EXIT ntstatus=`).
pub fn watch_exit_status(pid: u32) {
    EXIT_WATCH.lock().insert(pid, None);
}

/// The `NTSTATUS` a watched process ended with, once (`None` if it is not
/// watched or no status was recorded).
pub fn take_exit_status(pid: u32) -> Option<u32> {
    EXIT_WATCH.lock().remove(&pid).flatten().map(|(status, _)| status)
}

fn note_exit_status(pid: u32, status: NtStatus, by_process: bool) {
    if by_process {
        TRAILS.lock().retain(|k, _| k.0 != pid);
    }
    if WAITS_EVERY.load(core::sync::atomic::Ordering::Relaxed) != 0 {
        crate::kprintln!(
            "nt-waits: p{pid} {} status {:#x}",
            if by_process { "ends the process" } else { "ends a thread" },
            status.0
        );
    }
    if let Some(slot) = EXIT_WATCH.lock().get_mut(&pid)
        && !matches!(slot, Some((_, true)))
    {
        *slot = Some((status.0, by_process));
    }
}

fn with<R>(f: impl FnOnce(&mut NtState) -> R) -> R {
    let mut guard = STATE.lock();
    if guard.is_none() {
        make_state(&mut guard);
    }
    f(guard.as_mut().expect("made above"))
}

/// The NT state of the first NT use, made in a frame of its own: `with`
/// runs on deep paths (a page fault while an exception is dispatched, ADR
/// 0091), and the state built inline would make each of its frames large.
/// The state itself is built by [`build_state`], whose large frame is gone
/// again before the folder and file set-up below runs its deep VFS calls: a
/// debug kernel's 16 KiB stack overflowed when the desktop's compositor made
/// the first NT use with its first write to the desktop link (ADR 0155
/// addendum "browsing").
#[cold]
#[inline(never)]
fn make_state(slot: &mut Option<NtState>) {
    build_state(slot);
    let Some(state) = slot.as_mut() else { return };
    // The i686 ntdll every 32-bit process maps (ADR 0186).
    state.sys.ntdll32 = NTDLL32;
    // The logon the programs run in (ADR 0222).
    state.sys.logon = *LOGON.lock();
    state.sys.consent.hook = *UAC_ANSWER.lock();
    // The Windows folders on C: and the registry values that follow
    // them (ADR 0073), before file I/O attaches C:.
    layout::prepare(&mut state.sys);
    // File I/O: the VFS's volumes and drive letters (ADR 0067).
    io::attach(&mut state.sys);
    // The services that start at boot, once the state is there (ADR 0221).
    if let Ok(tid) = thread::spawn_named("nt-boot-services", boot_services, 0) {
        let _ = thread::detach(tid);
    }
    // An interactive logon's session (standard or elevated) has a shell holding the filtered
    // token (ADR 0222, 0235); the admin logon of the older recordings has none.
    if state.sys.logon != poly_personality_nt::security::Logon::Admin
        && let Ok(tid) = thread::spawn_named("nt-shell", shell_main, 0)
    {
        let _ = thread::detach(tid);
    }
    if INTERACTIVE.load(core::sync::atomic::Ordering::Relaxed) {
        let bottom = TASKBAR_BOTTOM.load(core::sync::atomic::Ordering::Relaxed);
        let display = if bottom {
            poly_win32k::metrics::Display::INTERACTIVE_BOTTOM
        } else {
            poly_win32k::metrics::Display::INTERACTIVE
        };
        match *DISPLAY.lock() {
            Some(((w, h), p)) => {
                let d = poly_win32k::metrics::Display::interactive_at(w, h, p, bottom);
                state.sys.win32k.wm.set_system_dpi(poly_win32k::dpiscale::dpi_of(p));
                state.sys.win32k.wm.set_display(d);
            }
            None => state.sys.win32k.wm.set_display(display),
        }
    }
}

/// The NT state with nothing set up yet, into `slot` (see [`make_state`]).
#[cold]
#[inline(never)]
fn build_state(slot: &mut Option<NtState>) {
    *slot = Some(NtState {
        sys: registry::boot_system(),
        processes: BTreeMap::new(),
        sections: Sections::default(),
        ctl: BTreeMap::new(),
        timers: BTreeMap::new(),
        created: BTreeMap::new(),
        finished: BTreeMap::new(),
        peak: BTreeMap::new(),
        private_peak: BTreeMap::new(),
    });
}

/// Run `f` on the NT state if the first NT use made it already.
fn with_existing<R>(f: impl FnOnce(&mut NtState) -> R) -> Option<R> {
    STATE.lock().as_mut().map(f)
}

/// Whether `pid` is an NT process the kernel has set up.
pub fn is_nt_process(pid: u32) -> bool {
    with(|s| s.processes.contains_key(&ProcessId(pid)))
}

/// The calling thread's view of the kernel for one system call.
struct Kernel {
    pid: ProcessId,
    tid: ThreadRef,
    memory: Arc<Memory>,
    /// Set by `NtTerminateProcess`, acted on after the call returns.
    exit: Option<NtStatus>,
    /// Set by `NtTerminateThread(NtCurrentThread)`, acted on after the call.
    exit_thread: Option<NtStatus>,
    /// Exception dispatch's requests (ADR 0068).
    seh: exception::Pending,
}

impl Kernel {
    fn new(pid: ProcessId, tid: ThreadRef, memory: Arc<Memory>) -> Kernel {
        Kernel { pid, tid, memory, exit: None, exit_thread: None, seh: exception::Pending::default() }
    }
}

impl NtKernel for Kernel {
    fn read_user(&mut self, addr: u64, buf: &mut [u8]) -> Result<(), UserFault> {
        crate::arch::user::copy_from_user(buf, addr).map_err(|_| UserFault)
    }

    fn write_user(&mut self, addr: u64, data: &[u8]) -> Result<(), UserFault> {
        crate::arch::user::copy_to_user(addr, data).map_err(|_| UserFault)
    }

    fn caller(&self) -> Caller {
        Caller::user(self.pid, self.tid)
    }

    fn with_state<R>(&mut self, f: impl FnOnce(&mut NtSystem, &mut NtProcess, &mut dyn Backend) -> R) -> R {
        let memory = &self.memory;
        with(|s| {
            let proc = s.processes.get_mut(&self.pid).expect("an NT process");
            let mut b = MemBackend { memory, sections: &mut s.sections };
            f(&mut s.sys, proc, &mut b)
        })
    }

    fn with_process<R>(
        &mut self,
        pid: ProcessId,
        f: impl FnOnce(&mut NtSystem, &mut NtProcess, &mut dyn Backend) -> R,
    ) -> Option<R> {
        let memory = io::memory_of(pid.0)?;
        with(|s| {
            let proc = s.processes.get_mut(&pid)?;
            let mut b = MemBackend { memory: &memory, sections: &mut s.sections };
            Some(f(&mut s.sys, proc, &mut b))
        })
    }

    fn terminate_process(&mut self, status: NtStatus) {
        note_exit_status(self.pid.0, status, true);
        self.exit = Some(status);
    }

    fn terminate_current_thread(&mut self, status: NtStatus) {
        with(|s| s.ctl.entry(self.tid).or_default().exit_status = Some(status));
        self.exit_thread = Some(status);
    }

    fn create_thread(
        &mut self,
        req: poly_personality_nt::ThreadCreate,
    ) -> Result<poly_personality_nt::ThreadCreated, NtStatus> {
        sched::create_thread(self.pid, self.tid, &self.memory, req)
    }

    fn create_process(
        &mut self,
        req: poly_personality_nt::ProcessCreate,
    ) -> Result<poly_personality_nt::ProcessCreated, NtStatus> {
        create_process(self.caller(), req)
    }

    fn terminate_thread(&mut self, thread: ThreadRef, status: NtStatus) -> Result<(), NtStatus> {
        sched::terminate_other(self.pid, thread, status)
    }

    fn terminate_other_process(&mut self, pid: ProcessId, status: NtStatus) -> Result<(), NtStatus> {
        sched::terminate_process_by_id(pid, status)
    }

    fn suspend_thread(&mut self, thread: ThreadRef) -> Result<u32, NtStatus> {
        sched::suspend(self.pid, thread)
    }

    fn resume_thread(&mut self, thread: ThreadRef) -> Result<u32, NtStatus> {
        sched::resume(self.pid, &self.memory, thread)
    }

    fn current_processor(&mut self) -> u32 {
        crate::thread::this_cpu() as u32
    }

    fn thread_affinity(&mut self, thread: ThreadRef) -> Result<u64, NtStatus> {
        let id = sched::kernel_thread(self.pid, self.tid, thread)?;
        let mask = crate::thread::affinity(id).ok_or(poly_ntobj::status::STATUS_INVALID_CID)?;
        Ok(mask.intersection(crate::thread::online_cpus()).bits())
    }

    fn set_thread_affinity(&mut self, thread: ThreadRef, mask: u64) -> Result<(), NtStatus> {
        let id = sched::kernel_thread(self.pid, self.tid, thread)?;
        let cpus = crate::thread::CpuSet::from_bits(mask).intersection(crate::thread::online_cpus());
        if cpus.is_empty() {
            return Err(poly_ntobj::status::STATUS_INVALID_PARAMETER);
        }
        crate::thread::set_affinity(id, cpus).map_err(|_| poly_ntobj::status::STATUS_INVALID_PARAMETER)
    }

    fn suspend_process(&mut self, pid: ProcessId) -> Result<(), NtStatus> {
        sched::suspend_process(pid)
    }

    fn resume_process(&mut self, pid: ProcessId) -> Result<(), NtStatus> {
        sched::resume_process(pid, &self.memory)
    }

    fn get_context(&mut self, thread: ThreadRef) -> Result<NtContext, NtStatus> {
        sched::get_context(self.tid, thread)
    }

    fn set_context(&mut self, thread: ThreadRef, ctx: &NtContext, want: u32) -> Result<(), NtStatus> {
        sched::set_context(self.tid, thread, ctx, want)
    }

    fn wait(&mut self, id: WaitId, timeout: NtTimeout, alertable: bool) -> NtStatus {
        // What this call completed for other threads is delivered before it
        // blocks, not after it ends: `TransactNamedPipe` writes the request
        // that wakes the server's pending read and then waits for the reply,
        // and the reply only comes once the server has seen the request
        // (a zero-length request met a pending read: both sides waited for ever).
        io::after_call();
        sched::wait(self.pid, self.tid, id, timeout, alertable)
    }

    fn arm_timer(&mut self, timer: ObjectId, due: NtTimeout, period: u32, apc: Option<Apc>) -> Result<bool, NtStatus> {
        sched::arm_timer(self.pid, self.tid, timer, due, period, apc)
    }

    fn disarm_timer(&mut self, timer: ObjectId) -> Result<bool, NtStatus> {
        sched::disarm_timer(timer)
    }

    fn queue_apc(&mut self, thread: ThreadRef, apc: Apc) -> Result<(), NtStatus> {
        sched::queue_apc(thread, apc)
    }

    fn test_alert(&mut self) -> NtStatus {
        let status = sched::test_alert(self.pid, self.tid);
        // After NtContinue(.., TestAlert): the APC resumes the loaded
        // context with its own RAX, not STATUS_USER_APC (ADR 0068).
        if status == poly_ntobj::status::STATUS_USER_APC
            && let Some(rax) = self.seh.rax
        {
            with(|s| {
                if let Some(saved) = s.ctl.get_mut(&self.tid).and_then(|c| c.apc_saved.as_mut()) {
                    saved.rax = rax;
                }
            });
        }
        status
    }

    fn delay(&mut self, timeout: NtTimeout, alertable: bool) -> NtStatus {
        sched::delay(self.pid, self.tid, timeout, alertable)
    }

    fn yield_execution(&mut self) -> NtStatus {
        if thread::yield_now() {
            poly_ntobj::status::STATUS_SUCCESS
        } else {
            poly_ntobj::status::STATUS_NO_YIELD_PERFORMED
        }
    }

    fn resume_apc(&mut self) -> NtStatus {
        // The interrupted context's RAX comes back in full (it may be one
        // NtContinue loaded), not as a 32-bit status.
        let rax = with(|s| s.ctl.get(&self.tid).and_then(|c| c.apc_saved.map(|r| r.rax)));
        self.seh.rax = rax;
        sched::resume_apc(self.tid)
    }

    fn load_context(&mut self, ctx: &poly_seh::Context, flags: u32) -> Result<(), NtStatus> {
        if let Some(rax) = exception::load(ctx, flags)? {
            self.seh.rax = Some(rax);
        }
        Ok(())
    }

    fn exception_delivered(&mut self, record: &poly_seh::ExceptionRecord, ctx: &poly_seh::Context) {
        if TRAIL_LEN.load(core::sync::atomic::Ordering::Relaxed) != 0
            && poly_personality_nt::trace::writes_trail(record.code)
            && selected(self.pid.0)
        {
            write_trail(self.pid.0, self.tid.0 as u32, record.code);
        }
        let words = EXCEPTIONS.load(core::sync::atomic::Ordering::Relaxed);
        if words != 0 {
            let memory = EXCEPTION_MEMORY.load(core::sync::atomic::Ordering::Relaxed) as usize;
            exception::report_delivered(self.pid, self.tid, record, ctx, words as usize, memory);
        }
    }

    fn unhandled_exception(&mut self, record: &poly_seh::ExceptionRecord, ctx: &poly_seh::Context) {
        self.seh.unhandled = Some(alloc::boxed::Box::new((*record, ctx.clone())));
    }

    fn trace(&mut self, values: [u64; 3]) {
        crate::kprintln!("nt: pid {} PolyTrace {:#x} {:#x} {:#x}", self.pid.0, values[0], values[1], values[2]);
    }

    fn debug_print(&mut self, text: &[u8]) {
        crate::kprintln!("nt: pid {}: {}", self.pid.0, alloc::string::String::from_utf8_lossy(text).trim_end());
    }

    fn physical_memory(&self) -> Option<(u64, u64)> {
        const PAGE: u64 = 4096;
        let (total, free) =
            crate::frames::FRAMES.lock().as_ref().map_or((0, 0), |f| (f.total_frames() * PAGE, f.free_frames() * PAGE));
        // As `/proc/meminfo`'s MemAvailable: free memory and the clean pages of the cache.
        let c = crate::fs::cache::cache().stats();
        let clean = (c.pages as u64).saturating_sub(c.dirty as u64) * PAGE;
        (total != 0).then_some((total, (free + clean).min(total)))
    }

    fn random_bytes(&mut self, buf: &mut [u8]) -> bool {
        crate::random::fill(buf);
        true
    }

    fn start_service_host(&mut self) {
        start_service_host();
    }

    fn system_time(&self) -> u64 {
        registry::filetime_now()
    }

    fn monotonic_100ns(&self) -> u64 {
        crate::time::now_ns() / 100
    }

    fn processor_count(&self) -> u32 {
        crate::thread::online_cpus().len() as u32
    }

    fn process_times(&self, pid: ProcessId) -> Option<[u64; 3]> {
        let Some(created) = with(|s| s.created.get(&pid).copied()) else {
            return with(|s| s.finished.get(&pid).copied());
        };
        let cpu = crate::process::find(pid.0).map(|p| crate::cputime::process(&p)).unwrap_or_default();
        let seen = with(|s| {
            let peak = s.peak.entry(pid).or_insert([0, 0]);
            peak[0] = peak[0].max(cpu.system_ns / 100);
            peak[1] = peak[1].max(cpu.user_ns / 100);
            *peak
        });
        Some([created, seen[0], seen[1]])
    }

    fn processes(&mut self) -> Vec<poly_personality_nt::proclist::ProcessSummary> {
        // A process whose exit status is set is ending: no longer listed.
        with(|s| {
            s.processes
                .values()
                .filter(|p| p.exit_status.is_none())
                .map(poly_personality_nt::proclist::ProcessSummary::of)
                .collect()
        })
    }

    fn memory_counters(&self, pid: ProcessId) -> Option<poly_personality_nt::threads::VmCounters> {
        let memory = io::memory_of(pid.0)?;
        let (resident, cached, shared) = memory.page_counts();
        // Private usage is the commit charge of the process's private memory (sheet of
        // `K32GetProcessMemoryInfo`: committing 16 MiB raises it before a page is touched), or
        // its private resident pages where the NT state does not know it.
        let resident_private = resident.saturating_sub(cached + shared);
        let committed = with(|s| s.processes.get(&pid).map(|p| p.vm.private_committed_bytes() / 4096));
        let private = committed.unwrap_or(resident_private);
        let (faults, peak_resident) = crate::process::find(pid.0).map_or((0, 0), |p| p.cpu.memory_counts());
        let peak_private = with(|s| {
            let p = s.private_peak.entry(pid).or_insert(0);
            *p = (*p).max(private);
            *p
        });
        Some(poly_personality_nt::threads::VmCounters { faults, resident, peak_resident, private, peak_private })
    }

    fn thread_times(&self, pid: ProcessId, thread: ThreadRef) -> Option<[u64; 3]> {
        // The thread's own start is not kept: its process's creation time stands in for it.
        let created = with(|s| s.created.get(&pid).copied())?;
        let cpu = crate::cputime::thread(pid.0, thread.0 as u32)?;
        Some([created, cpu.system_ns / 100, cpu.user_ns / 100])
    }

    fn save_hive(&mut self, file: &str, data: &[u8]) -> Result<(), NtStatus> {
        registry::save(file, data)
    }

    fn socket_create(
        &mut self,
        domain: poly_personality_nt::afd::Domain,
        ty: poly_personality_nt::afd::SockType,
        protocol: poly_personality_nt::afd::Protocol,
    ) -> Result<Arc<dyn poly_personality_nt::afd::NtSocket>, NtStatus> {
        afd::create(domain, ty, protocol)
    }

    fn socket_poll(
        &mut self,
        socks: &[(Arc<dyn poly_personality_nt::afd::NtSocket>, poly_personality_nt::afd::Readiness)],
        wait: poly_personality_nt::afd::SockWait,
    ) -> Result<Vec<poly_personality_nt::afd::Readiness>, NtStatus> {
        Ok(afd::poll_sockets(socks, wait))
    }

    fn socket_pend(
        &mut self,
        io: poly_personality_nt::afd::PendIo,
    ) -> Result<(), alloc::boxed::Box<poly_personality_nt::afd::PendIo>> {
        afd::pend(io)
    }

    fn net_info(&self) -> (Vec<[u8; 4]>, String) {
        afd::net_info()
    }

    fn audio_device(&mut self) -> Option<poly_audio::nt::DeviceInfo> {
        audio::device()
    }

    fn audio_open(
        &mut self,
        format: poly_audio::Format,
        buffer_frames: u32,
    ) -> Result<Arc<dyn poly_personality_nt::audio::NtAudioStream>, NtStatus> {
        audio::open(format, buffer_frames)
    }

    fn audio_pend(
        &mut self,
        w: poly_personality_nt::audio::AudioWait,
    ) -> Result<(), poly_personality_nt::audio::AudioWait> {
        audio::pend(w)
    }

    fn net_interfaces(&self) -> Vec<poly_personality_nt::afd::IfInfo> {
        afd::net_interfaces()
    }
}

/// Route an NT process's system call (its `SyscallHook`).
pub fn syscall(process: &Process, regs: &mut SyscallRegs) -> Outcome {
    let Some(memory) = user::current_memory() else {
        regs.rax = u64::from(poly_personality_nt::STATUS_NOT_IMPLEMENTED);
        return Outcome::Handled;
    };
    let tid = user::current_tid().unwrap_or(process.pid);
    let mut k = Kernel::new(ProcessId(process.pid), ThreadRef(u64::from(tid)), memory);
    let trace = TRACE.load(core::sync::atomic::Ordering::Relaxed);
    let trail = TRAIL_LEN.load(core::sync::atomic::Ordering::Relaxed);
    note_command_line(process.pid);
    let traced =
        (trace != 0 || trail != 0 || apitrace::wanted()).then(|| selected(process.pid)).filter(|&s| s).map(|_| {
            if crate::arch::user::compat() {
                poly_personality_nt::trace::begin32(&mut k, regs)
            } else {
                poly_personality_nt::trace::begin(&mut k, regs)
            }
        });
    // A 32-bit thread's call comes in the 32-bit convention and is converted (ADR 0186).
    let outcome = if crate::arch::user::compat() {
        poly_personality_nt::wow64::dispatch32(&mut k, regs, |k, regs| poly_personality_nt::dispatch_with(k, regs))
    } else {
        poly_personality_nt::dispatch_with(&mut k, regs)
    };
    if let Some(call) = traced {
        let status = regs.rax as u32;
        if crate::arch::user::compat() && apitrace::wanted() {
            let teb =
                with(|s| s.processes.get(&ProcessId(process.pid))?.thread(ThreadRef(u64::from(tid))).map(|t| t.teb))
                    .unwrap_or(0);
            apitrace::arm_if_match(process.pid, tid, call.object.as_deref(), teb, regs);
        }
        if trace != 0 && poly_personality_nt::trace::wanted(&call, status, trace == 2) {
            crate::kprintln!("{}", poly_personality_nt::trace::render(process.pid, tid, &call, status));
        }
        if trail != 0 && !TRAIL_SKIP.lock().split(',').any(|n| n == call.name) {
            let mut line = poly_personality_nt::trace::render(process.pid, tid, &call, status);
            // When it returned (µs since boot), and what a performance counter read gave: the
            // order and spacing of a thread's calls and the times it saw.
            line.push_str(&alloc::format!(" @{}us", crate::time::now_ns() / 1000));
            if call.service == Some(poly_personality_nt::services::Service::QueryPerformanceCounter) {
                let mut b = [0u8; 8];
                if user::copy_from_user(&mut b, call.args[0]).is_ok() {
                    line.push_str(&alloc::format!(" = {}", u64::from_le_bytes(b)));
                }
            }
            TRAILS.lock().entry((process.pid, tid)).or_default().push(line, trail);
        }
    }
    // Any wait a signalling call satisfied: wake those threads.
    sched::drain_wakes();
    // File I/O requests it queued or completed (ADR 0067).
    io::after_call();
    // Console output and events (ADR 0080).
    console::drive();
    // What win32k has for the compositor (ADR 0131).
    link::after_call();
    if let Some(status) = k.exit {
        sched::terminate_siblings(ProcessId(process.pid), ThreadRef(u64::from(tid)), status);
        let _ = user::request_exit(ExitStatus::Exited(status.0 as u8));
    } else if let Some(status) = k.exit_thread {
        let _ = user::request_exit(ExitStatus::Exited(status.0 as u8));
    }
    // A context loaded by NtContinue or exception dispatch returns its
    // RAX in full; an unhandled exception ends the process here.
    if let Some(rax) = exception::finish(k) {
        regs.rax = rax;
    }
    outcome
}

/// A PE executable started as an NT process: its first thread's entry.
pub struct Start {
    pub entry: crate::arch::user::Entry,
    /// The GS base the thread runs with (its TEB).
    pub teb: u64,
    /// The thread id the first thread runs under (its TEB, thread object and `ClientId` were made
    /// for it). Not the process id for a process made by `NtCreateUserProcess`: Windows gives
    /// the first thread an id of its own.
    pub tid: u32,
}

/// How an NT process was started: its executable's DOS path and its
/// arguments (after the program name), for its process parameters
/// (ADR 0073).
#[derive(Clone, Debug, Default)]
pub struct Launch {
    pub image_path: String,
    pub args: Vec<String>,
}

impl Launch {
    /// The launch of the executable at VFS path `path` with `argv`
    /// (`argv[0]`, the program name, is replaced by the DOS path).
    pub fn of(path: &[u8], argv: &[&[u8]]) -> Launch {
        Launch {
            image_path: layout::dos_path(path),
            // A path naming a file reaches the program as its DOS path (Files opening a
            // download with a Windows program, ADR 0234).
            args: argv.iter().skip(1).map(|a| layout::dos_argument(String::from_utf8_lossy(a).into_owned())).collect(),
        }
    }

    /// An image the kernel built itself (a test) has no file; it is named
    /// as if it were in `System32`.
    fn unnamed() -> Launch {
        Launch { image_path: "C:\\Windows\\System32\\poly-image.exe".into(), args: Vec::new() }
    }
}

/// Set up `process` (already made with [`Process::new`] and personality
/// `Nt`) to run the PE image `file` in `memory`, as its first thread `tid`.
/// Returns where to start it. The caller spawns the thread with
/// [`user::spawn_nt`] and [`DEFAULT_HOOK`](user::DEFAULT_HOOK).
pub fn start(process: &Arc<Process>, memory: &Arc<Memory>, file: &[u8], tid: u32) -> Result<Start, NtStatus> {
    start_with(process, memory, file, tid, &Launch::unnamed())
}

/// [`start`] with the executable's path and arguments, which go into the
/// process parameters with the default environment (ADR 0073).
pub fn start_with(
    process: &Arc<Process>,
    memory: &Arc<Memory>,
    file: &[u8],
    tid: u32,
    launch: &Launch,
) -> Result<Start, NtStatus> {
    // Its standard handles come from its descriptors 0-2 (ADR 0080).
    let sources = console::std_sources(process);
    start_with_std(process, memory, file, tid, launch, &sources)
}

/// [`start_with`] with the sources of the standard handles given.
pub fn start_with_std(
    process: &Arc<Process>,
    memory: &Arc<Memory>,
    file: &[u8],
    tid: u32,
    launch: &Launch,
    sources: &[console::StdSource; 3],
) -> Result<Start, NtStatus> {
    let params = with(|s| {
        let args: Vec<&str> = launch.args.iter().map(String::as_str).collect();
        poly_personality_nt::params::for_program(&launch.image_path, &args, layout::environment(&s.sys))
    });
    let image = poly_personality_nt::image::ImageSection::from_file(file)?;
    start_params(process, memory, image, tid, &params, sources, None).map(|(start, _)| start)
}

/// Who gets handles to a new process and its first thread, with which
/// access (`NtCreateUserProcess`, ADR 0079), and whether the new process
/// inherits that creator's inheritable handles (ADR 0089).
struct HandlesFor {
    caller: Caller,
    process_access: u32,
    thread_access: u32,
    inherit_handles: bool,
    /// The primary token it gets, else a copy of the creator's (ADR 0171).
    token: Option<u64>,
    /// ADR 0169: only these handles (`PROC_THREAD_ATTRIBUTE_HANDLE_LIST`),
    /// the jobs it is created in, whether it joins its creator's, and
    /// whether it may make memory executable.
    inherit_only: Option<Vec<poly_ntobj::Handle>>,
    jobs: Vec<u64>,
    join_creator_jobs: bool,
    mitigation: poly_personality_nt::MitigationState,
    /// The station and desktop it starts on (ADR 0192).
    desktop: poly_personality_nt::winsta::Start,
    /// Its creator's error mode (`SetErrorMode`), which it starts with.
    error_mode: u32,
    /// The descriptors of its process and first thread objects (`lpProcessAttributes`,
    /// `lpThreadAttributes`), applied once the creator's handles are open.
    process_security: Option<Vec<u8>>,
    thread_security: Option<Vec<u8>>,
    /// The process it is a child of (`PROC_THREAD_ATTRIBUTE_PARENT_PROCESS`): its parent and the
    /// source of its token; else the creator.
    parent: Option<ProcessId>,
}

impl HandlesFor {
    /// The process it is a child of and inherits its token from.
    fn parent(&self) -> ProcessId {
        self.parent.unwrap_or(self.caller.process)
    }
}

/// Handles to a new process and its first thread.
type ChildHandles = (poly_ntobj::Handle, poly_ntobj::Handle);

/// Set up `process` to run `file` with the process parameters `params`
/// (ADR 0073) and the standard handles `sources` (ADR 0080); with
/// `handles`, also open handles to its process and first thread for the
/// creator, before anything runs (ADR 0079), give it the creator's
/// inheritable handles first if asked, the creator's console, and the
/// standard handles the creator chose (ADR 0089).
fn start_params(
    process: &Arc<Process>,
    memory: &Arc<Memory>,
    image: poly_personality_nt::image::ImageSection,
    tid: u32,
    params: &poly_personality_nt::params::Parameters,
    sources: &[console::StdSource; 3],
    handles: Option<&HandlesFor>,
) -> Result<(Start, Option<ChildHandles>), NtStatus> {
    let pid = ProcessId(process.pid);
    let thread = ThreadRef(u64::from(tid));
    if NTDLL.is_empty() {
        crate::kprintln!("nt: this kernel was built without ntdll.dll (build it with cargo xtask)");
        return Err(NtStatus(0xC000_0135)); // STATUS_DLL_NOT_FOUND (ntstatus.h)
    }
    // File I/O completions are written into this memory (ADR 0067).
    io::register(process.pid, memory);
    // A console program gets a console (ADR 0080).
    let console_app = image.info.optional.subsystem == poly_pe::subsystem::WINDOWS_CUI;
    let started = with(|s| {
        s.processes.insert(pid, NtProcess::new(pid));
        s.created.insert(pid, registry::filetime_now());
        s.finished.remove(&pid);
        s.peak.remove(&pid);
        let proc = s.processes.get_mut(&pid).expect("just inserted");
        proc.parent = handles.map_or(0, |h| h.parent().0);
        if let Some(h) = handles {
            proc.set_mitigation(h.mitigation);
            s.sys.winsta.begin(pid, h.desktop.clone());
        }
        match handles.map_or(0, |h| h.error_mode) {
            0 => {}
            mode => {
                s.sys.proc_attrs.insert(pid, poly_personality_nt::procattrs::ProcAttrs::new(mode));
            }
        }
        proc.image_name = s.sys.io.dos_file_name(&params.image_path);
        let mut b = MemBackend { memory, sections: &mut s.sections };
        // Its creator's inheritable handles, before any other (ADR 0089).
        let inherit_from = handles.filter(|h| h.inherit_handles).map(|h| h.caller.process);
        let creator = console::FromCreator {
            given: params.given_std_handles(),
            inherited: if handles.is_some() { params.inherited_std_handles() } else { [0; 3] },
            console: handles.and_then(|h| s.sys.io.console_of_process(h.caller.process)),
        };
        let only = handles.and_then(|h| h.inherit_only.as_deref());
        let start =
            exec::start_process_listed(&mut s.sys, proc, &mut b, image, NTDLL, None, thread, inherit_from, only);
        let start = start.and_then(|ps| {
            // Its token (a copy of its creator's, or the one given) and the
            // descriptors of its objects (ADR 0171).
            poly_personality_nt::security::inherit_token(
                &mut s.sys,
                pid,
                handles.map(HandlesFor::parent),
                handles.and_then(|h| h.token),
                thread,
            )?;
            // Its session, from the token (ADR 0222).
            poly_personality_nt::security::write_session_id(&s.sys, proc, &mut b)?;
            poly_personality_nt::security::assign_process_security(
                &mut s.sys,
                pid,
                handles.map(|h| &h.caller),
                proc.object,
                proc.threads.first().map(|t| t.object),
            );
            // Its first thread has not run yet (job notifications, ADR 0169).
            s.sys.jobs.mark_unstarted(pid);
            // Its creator's jobs and the ones it was made for (ADR 0169).
            if let Some(h) = handles {
                s.sys.jobs.process_created(
                    &mut s.sys.io,
                    &mut s.sys.objects,
                    h.caller.process,
                    pid,
                    h.join_creator_jobs,
                    &h.jobs,
                )?;
            }
            // KUSER_SHARED_DATA at 0x7FFE0000 (ADR 0155).
            exec::map_user_shared_data(proc, &mut b, &user_shared_facts())?;
            // The process parameters: image path, command line,
            // environment and current directory (ADR 0073, 0079).
            let base = poly_personality_nt::params::write(proc, &mut b, ps.peb, params)?;
            // Its console and standard handles (ADR 0080, 0089).
            let (connection, std) = console::setup(&mut s.sys, &mut b, pid, thread, console_app, sources, creator)?;
            poly_personality_nt::params::write_handles_for(&proc.layout(), &mut b, base, connection, std)?;
            // Handles for its creator (NtCreateUserProcess, ADR 0079).
            let opened = match handles {
                Some(h) => {
                    let opened =
                        exec::child_handles(&mut s.sys, &h.caller, pid, thread, h.process_access, h.thread_access)?;
                    // The creator's handles are open: now the descriptors it asked for apply.
                    poly_personality_nt::security::assign_explicit_process_security(
                        &mut s.sys,
                        pid,
                        Some(&h.caller),
                        h.token.is_some(),
                        proc.object.map(|o| (o, h.process_security.as_deref())),
                        proc.threads.first().map(|t| (t.object, h.thread_security.as_deref())),
                    );
                    Some(opened)
                }
                None => None,
            };
            Ok((ps, opened))
        });
        match start {
            Ok((ps, opened)) => Ok((
                Start {
                    // The first thread starts in ntdll's LdrInitializeThunk
                    // with the image entry, its argument (the PEB) and the
                    // image base (ADR 0071's start convention).
                    entry: crate::arch::user::Entry {
                        rip: ps.entry,
                        rsp: ps.rsp,
                        args: [ps.start_routine, ps.argument, ps.image_base],
                    },
                    teb: ps.teb,
                    tid,
                },
                opened,
            )),
            Err(e) => {
                s.created.remove(&pid);
                let mut proc = s.processes.remove(&pid).expect("just inserted");
                let mut b = MemBackend { memory, sections: &mut s.sections };
                exec::process_exit(&mut s.sys, &mut proc, &mut b);
                Err(e)
            }
        }
    });
    if started.is_err() {
        io::unregister(process.pid);
    }
    started
}

/// `NtCreateUserProcess` (ADR 0079): a new NT process running `req.image`
/// with `req.params`, the creator's console and standard handles (or those
/// it chose) and, if asked, its inheritable handles (ADR 0089), handles to
/// it and its first thread in the creator's table, and its first thread
/// started — or left suspended until `NtResumeThread` (ADR 0089).
fn create_process(
    creator: Caller,
    req: poly_personality_nt::ProcessCreate,
) -> Result<poly_personality_nt::ProcessCreated, NtStatus> {
    use crate::user::memory::Layout;
    use poly_binfmt::{Arch, Bits, Format};
    let memory = Arc::new(Memory::new(Layout::default()).map_err(|_| poly_ntobj::status::STATUS_NO_MEMORY)?);
    let creator_process = user::current_process();
    let traced = creator_process.as_ref().is_some_and(|p| p.traced);
    // The child shares its creator's console: the standard handles it
    // does not get from its creator come from the creator's descriptors
    // 0-2 (ADR 0080), else from the creator's console (ADR 0089).
    let sources = match &creator_process {
        Some(p) => console::std_sources(p),
        None => [console::StdSource::None, console::StdSource::None, console::StdSource::None],
    };
    let pid = crate::process::alloc_nt_id();
    // The first thread's id is its own (GetThreadId of the main thread differs from the process id).
    let tid = crate::process::alloc_nt_id();
    let format = Format::Pe { bits: Bits::B64, arch: Arch::X86_64 };
    // The process that created it (or the one it was created as a child of) is its parent in
    // /proc (ADR 0230).
    let mut nt = Process::new_nt(pid, format, traced);
    nt.ppid = req.parent.map_or_else(|| creator_process.as_ref().map_or(0, |p| p.pid), |p| p.0);
    let process = Arc::new(nt);
    let want = HandlesFor {
        caller: creator,
        process_access: req.process_access,
        thread_access: req.thread_access,
        inherit_handles: req.inherit_handles,
        token: req.token,
        inherit_only: req.inherit_only,
        jobs: req.jobs,
        join_creator_jobs: req.join_creator_jobs,
        mitigation: req.mitigation,
        desktop: req.desktop,
        error_mode: req.error_mode,
        process_security: req.process_security,
        thread_security: req.thread_security,
        parent: req.parent,
    };
    let (start, handles) = start_params(&process, &memory, req.image, tid, &req.params, &sources, Some(&want))?;
    let (ph, th) = handles.expect("asked for");
    let first = ThreadRef(u64::from(tid));
    let created = poly_personality_nt::ProcessCreated {
        process: ph,
        thread: th,
        client: poly_personality_nt::ClientId { process: ProcessId(pid), thread: first },
    };
    if req.suspended {
        // CREATE_SUSPENDED (ADR 0089): the first thread starts when its
        // suspend count drops to zero (`sched::resume`). Until then a thread
        // another process makes in it does not end it by leaving.
        process.hold();
        with(|s| {
            let c = s.ctl.entry(first).or_default();
            c.suspend_count = 1;
            c.deferred_start = Some((start.entry, start.teb));
            c.deferred_process = Some((process, memory));
        });
        return Ok(created);
    }
    match start_first_thread(&process, &memory, &start) {
        Ok(()) => Ok(created),
        Err(e) => {
            with(|s| {
                let _ = s.sys.objects.close(&creator, ph);
                let _ = s.sys.objects.close(&creator, th);
            });
            Err(e)
        }
    }
}

/// Whether NT process `pid` is a 32-bit one (ADR 0186).
fn is_wow64(pid: u32) -> bool {
    with_existing(|s| s.processes.get(&ProcessId(pid)).is_some_and(|p| p.wow64)).unwrap_or(false)
}

/// Start a thread of NT process `process` in ring 3 at `entry` with its TEB at `teb`: a 64-bit
/// one with GS based at the TEB, or, in a 32-bit process, one in compatibility mode with FS
/// based at its 32-bit TEB (ADR 0186). `tid`: the thread id already chosen, if any.
pub(super) fn spawn_thread(
    process: &Arc<Process>,
    memory: &Arc<Memory>,
    entry: user::Entry,
    teb: u64,
    hook: user::SyscallHook,
    tid: Option<u32>,
) -> Result<crate::thread::ThreadId, crate::thread::SpawnError> {
    let (p, m) = (Arc::clone(process), Arc::clone(memory));
    if is_wow64(process.pid) {
        return user::spawn_nt32(p, m, entry, teb, hook, tid);
    }
    match tid {
        Some(t) => user::spawn_nt_as(p, m, entry, teb, hook, t),
        None => user::spawn_nt(p, m, entry, teb, hook),
    }
}

/// Start a new NT process's first thread in ring 3 at `start`; if it
/// cannot start, the process ends.
pub(super) fn start_first_thread(process: &Arc<Process>, memory: &Arc<Memory>, start: &Start) -> Result<(), NtStatus> {
    // The job notifications count the first thread as run from here on (ADR 0169).
    let pid = ProcessId(process.pid);
    with(|s| s.sys.jobs.started(pid));
    match spawn_thread(process, memory, start.entry, start.teb, user::DEFAULT_HOOK, Some(start.tid)) {
        Ok(kthread) => {
            // The creator waits on the process object, not the thread.
            let _ = thread::detach(kthread);
            Ok(())
        }
        Err(_) => {
            process_exit(process.pid, memory);
            Err(poly_ntobj::status::STATUS_NO_MEMORY)
        }
    }
}

pub use sched::wait_while_suspended;

/// Translate a thread's [`ExitStatus`] to the `NTSTATUS` its object reports.
fn exit_to_nt(status: ExitStatus) -> NtStatus {
    match status {
        ExitStatus::Exited(code) => NtStatus(u32::from(code)),
        ExitStatus::Faulted(vector) => exec::exception_status(vector),
        ExitStatus::Signaled { .. } => NtStatus(0xC000_0005), // STATUS_ACCESS_VIOLATION
    }
}

/// One thread of NT process `pid` has ended: free its stack and TEB, record
/// its exit status, signal its thread object and abandon its mutants (so
/// waiters wake). Called for every NT thread as it leaves, before it
/// detaches from its process.
pub fn thread_exit(pid: u32, tid: u32, status: ExitStatus, memory: &Arc<Memory>) {
    let tref = ThreadRef(u64::from(tid));
    let ended = with(|s| {
        if !s.processes.contains_key(&ProcessId(pid)) {
            return None;
        }
        let nt_status = s.ctl.get(&tref).and_then(|c| c.exit_status).unwrap_or_else(|| exit_to_nt(status));
        let proc = s.processes.get_mut(&ProcessId(pid)).expect("checked");
        let mut b = MemBackend { memory, sections: &mut s.sections };
        exec::thread_exit(&mut s.sys, proc, &mut b, tref, nt_status);
        s.ctl.remove(&tref);
        // Its pending I/O requests are cancelled (ADR 0067).
        s.sys.io.cancel_thread(tref);
        Some(nt_status)
    });
    // The last thread's status is the process's, unless NtTerminateProcess
    // gave one.
    if let Some(nt_status) = ended {
        note_exit_status(pid, nt_status, false);
    }
    sched::drain_wakes();
    io::drain();
}

/// The NT process `pid` has ended (its last thread is going): drop its
/// objects, views and handles. Its memory itself goes with `user::Memory`.
pub fn process_exit(pid: u32, memory: &Arc<Memory>) {
    // What it used, kept for the handles that outlive it (the last thread is still counted).
    let used = crate::process::find(pid).map(|p| crate::cputime::process(&p)).unwrap_or_default();
    if WAITS_EVERY.load(core::sync::atomic::Ordering::Relaxed) != 0 {
        crate::kprintln!("nt-waits: p{pid} ended at {} ms", crate::time::now_ns() / 1_000_000);
    }
    let mut dropped = Vec::new();
    let host_needed = with(|s| {
        if let Some(created) = s.created.remove(&ProcessId(pid)) {
            let cpu = used;
            const KEEP: usize = 4096;
            if s.finished.len() >= KEEP
                && let Some(oldest) = s.finished.keys().next().copied()
            {
                s.finished.remove(&oldest);
            }
            let seen = s.peak.get(&ProcessId(pid)).copied().unwrap_or([0, 0]);
            s.finished.insert(
                ProcessId(pid),
                [created, (cpu.system_ns / 100).max(seen[0]), (cpu.user_ns / 100).max(seen[1])],
            );
        }
        s.peak.remove(&ProcessId(pid));
        // A first thread that never started keeps no reference to the process.
        let unstarted: Vec<_> =
            s.processes.get(&ProcessId(pid)).map_or_else(Vec::new, |p| p.threads.iter().map(|t| t.thread).collect());
        for t in unstarted {
            if let Some(c) = s.ctl.get_mut(&t) {
                c.deferred_start = None;
                if let Some(d) = c.deferred_process.take() {
                    dropped.push(d);
                }
            }
        }
        if let Some(mut proc) = s.processes.remove(&ProcessId(pid)) {
            let mut b = MemBackend { memory, sections: &mut s.sections };
            exec::process_exit(&mut s.sys, &mut proc, &mut b);
        }
        // Its registry notifications go too (ADR 0066).
        s.sys.registry.process_ended(ProcessId(pid), &mut s.sys.objects);
        // Its service handles close, and a service it ran stops (ADR 0221).
        let now_ms = crate::time::now_ns() / 1_000_000;
        poly_personality_nt::scm::process_ended(&mut s.sys, ProcessId(pid), now_ms, registry::filetime_now())
    });
    // Dropped out of the lock: a memory map may sleep as it goes.
    drop(dropped);
    if host_needed {
        start_service_host();
    }
    // Its children go to its own parent (ADR 0230), so `/proc` links every
    // process to a living ancestor.
    adopt_children(pid);

    // Its file objects closed with its handles: deliver the cancellations.
    io::drain();
    // Jobs it kept alive (kill on close) end their other members (ADR 0169).
    io::kill_pending();
    // Its console handles too: a console it was the last on closes.
    console::drive();
    io::unregister(pid);
    sched::drain_wakes();
    registry::flush();
}

/// The processes whose parent is `pid`, which is ending, get `pid`'s parent (ADR 0230): an
/// installer's helper started by a short-lived elevated copy stays in the installer's tree.
fn adopt_children(pid: u32) {
    let Some(me) = crate::process::find(pid) else { return };
    let parent = crate::linux::task::parent_of(&me);
    for p in crate::process::all() {
        if p.pid != pid && crate::linux::task::parent_of(&p) == pid {
            p.adopted.store(parent, core::sync::atomic::Ordering::Relaxed);
        }
    }
}

/// `services.exe` is being started (ADR 0221): one start at a time.
static HOST_STARTING: core::sync::atomic::AtomicBool = core::sync::atomic::AtomicBool::new(false);

/// Start `C:\Windows\System32\services.exe`, the host of the service control manager (ADR 0221),
/// from a kernel thread of its own (the caller may hold the NT state).
pub fn start_service_host() {
    use core::sync::atomic::Ordering::SeqCst;
    if HOST_STARTING.swap(true, SeqCst) {
        return;
    }
    match thread::spawn_named("nt-services", services_main, 0) {
        Ok(tid) => {
            let _ = thread::detach(tid);
        }
        Err(_) => HOST_STARTING.store(false, SeqCst),
    }
}

fn services_main(_: usize) -> usize {
    let path = alloc::format!("{}/Windows/System32/services.exe", layout::C_PATH);
    let started = crate::program::prepare(path.as_bytes(), &[path.as_bytes()], &[], false).and_then(|p| {
        // The manager accepts this process, and only it, as its host.
        let pid = p.process().pid;
        with(|s| poly_personality_nt::scm::expect_host(&mut s.sys, ProcessId(pid)));
        p.start()
    });
    match started {
        Ok(p) => crate::kprintln!("nt: services.exe started (p{})", p.pid),
        Err(e) => crate::kprintln!("nt: services.exe could not start: {e}"),
    }
    HOST_STARTING.store(false, core::sync::atomic::Ordering::SeqCst);
    0
}

/// Start `C:\Windows\explorer.exe`, the stand-in of the session's shell (ADR 0222), with the
/// logon's filtered token: an elevated program finds it and starts a process de-elevated with a
/// copy of that token.
fn shell_main(_: usize) -> usize {
    if EXPLORER_EXE.is_empty() {
        return 0;
    }
    let path = alloc::format!("{}/Windows/explorer.exe", layout::C_PATH);
    let started = crate::program::prepare(path.as_bytes(), &[path.as_bytes()], &[], false).and_then(|p| {
        let pid = p.process().pid;
        if let Err(e) = with(|s| poly_personality_nt::security::become_shell(&mut s.sys, ProcessId(pid), ThreadRef(0)))
        {
            crate::kprintln!("nt: explorer.exe keeps its creator's token ({:#x})", e.0);
        }
        p.start()
    });
    match started {
        Ok(p) => {
            // The session's shell window answers as this process's (`GetShellWindow`).
            with(|s| {
                let tid = s.processes.get(&ProcessId(p.pid)).and_then(|q| q.threads.first()).map_or(0, |t| t.thread.0);
                s.sys.win32k.wm.set_shell_process(p.pid, tid as u32);
            });
            crate::kprintln!("nt: explorer.exe started (p{}) with the filtered token", p.pid)
        }
        Err(e) => crate::kprintln!("nt: explorer.exe could not start: {e}"),
    }
    0
}

/// At the first NT use: start the service host when the registry has services to start at boot
/// (ADR 0221: the auto-start services start with the Windows world).
fn boot_services(_: usize) -> usize {
    if with(|s| poly_personality_nt::scm::wants_host_at_boot(&mut s.sys)) {
        start_service_host();
    }
    0
}

/// A page fault the memory map could not resolve, in NT process `pid`: a
/// guard page may fire and a stack grow (the thread goes on), else it is an
/// exception. Returns whether the faulting instruction should be retried.
pub fn resolve_fault(pid: u32, tid: u32, memory: &Arc<Memory>, addr: u64) -> bool {
    with(|s| {
        let Some(proc) = s.processes.get_mut(&ProcessId(pid)) else { return false };
        let mut b = MemBackend { memory, sections: &mut s.sections };
        let tref = ThreadRef(u64::from(tid));
        match exec::access_fault(proc, &mut b, tref, addr) {
            vm::AccessFault::StackGrown { .. } => true,
            // Remembered for the exception it raises (ADR 0068).
            vm::AccessFault::Exception(status) => {
                s.ctl.entry(tref).or_default().page_fault = Some((addr, status));
                false
            }
        }
    })
}

/// Why a PE executable could not be started.
#[derive(Clone, Copy, Debug)]
#[allow(dead_code)] // read through Debug when a start fails
pub enum SpawnError {
    /// No memory for the address space.
    Memory,
    /// The image is not a loadable x64 PE (or the kernel has no `ntdll`):
    /// the `NTSTATUS`. Imports that cannot be bound end the started process
    /// instead, with the loader's status (ADR 0071).
    Image(NtStatus),
    /// The thread could not be started.
    Thread(thread::SpawnError),
}

/// Start the PE executable `file` in the already-made NT process
/// `process`, its first thread running the entry point. Returns `process`.
/// `launch` names it and gives its arguments (its process parameters,
/// ADR 0073).
pub fn spawn_pe_with(
    process: &Arc<Process>,
    image: poly_personality_nt::image::ImageSection,
    hook: user::SyscallHook,
    launch: &Launch,
) -> Result<(), SpawnError> {
    use crate::user::memory::Layout;
    start_waits_reporter();
    let memory = Arc::new(Memory::new(Layout::default()).map_err(|_| SpawnError::Memory)?);
    let pid = process.pid;
    let sources = console::std_sources(process);
    let params = with(|s| {
        let args: Vec<&str> = launch.args.iter().map(String::as_str).collect();
        poly_personality_nt::params::for_program(&launch.image_path, &args, layout::environment(&s.sys))
    });
    // Its main thread has an id of its own, not the process id.
    let tid = crate::process::alloc_nt_id();
    let start = start_params(process, &memory, image, tid, &params, &sources, None)
        .map(|(start, _)| start)
        .map_err(SpawnError::Image)?;
    match spawn_thread(process, &memory, start.entry, start.teb, hook, Some(start.tid)) {
        Ok(tid) => {
            let _ = thread::detach(tid);
            Ok(())
        }
        Err(e) => {
            process_exit(pid, &memory);
            Err(SpawnError::Thread(e))
        }
    }
}

/// What `KUSER_SHARED_DATA` is filled from when a process starts (ADR 0155).
fn user_shared_facts() -> poly_personality_nt::kuser::Facts {
    use core::arch::x86_64::__cpuid_count;
    // SAFETY: CPUID exists on every x86-64 processor; leaves beyond the maximum are not read.
    let cpu = unsafe {
        let max = __cpuid_count(0, 0).eax;
        let ext_max = __cpuid_count(0x8000_0000, 0).eax;
        let l1 = __cpuid_count(1, 0);
        let l7 = if max >= 7 { __cpuid_count(7, 0) } else { core::mem::zeroed() };
        let e1 = if ext_max >= 0x8000_0001 { __cpuid_count(0x8000_0001, 0) } else { core::mem::zeroed() };
        // The kernel's own XCR0 (what it enabled), when the processor has XSAVE enabled.
        let xcr0 = if l1.ecx >> 27 & 1 != 0 { core::arch::x86_64::_xgetbv(0) } else { 0 };
        poly_personality_nt::CpuId {
            leaf1_ecx: l1.ecx,
            leaf1_edx: l1.edx,
            leaf7_ebx: l7.ebx,
            leaf7_ecx: l7.ecx,
            ext1_ecx: e1.ecx,
            ext1_edx: e1.edx,
            xcr0,
        }
    };
    let pages = crate::frames::FRAMES.lock().as_ref().map_or(0, |f| f.total_frames());
    poly_personality_nt::kuser::Facts {
        system_time: registry::filetime_now(),
        uptime: crate::time::now_ns() / 100,
        processors: crate::thread::online_cpus().len() as u32,
        physical_pages: pages,
        cpu,
    }
}
